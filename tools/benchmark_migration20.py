#!/usr/bin/env python3
"""Actual Phase32 source populations, supplied to Python and BigInt cell engines.

Full record digests are transfer comparisons, not independent proofs. The phase
schedule is generated by the unchanged Python caller; this is not UI admission.
"""
from __future__ import annotations
import argparse,hashlib,importlib.util,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path[:0]=[str(ROOT/'src'),str(ROOT/'tools/nollm_visual_toolkit')]
from nollm_visual_toolkit import phase32_lab as phase32
from nollm_visual_toolkit.multiplicative import parse_cell_scale_text
spec=importlib.util.spec_from_file_location('m20_crosslang',ROOT/'tools/nollm_visual_toolkit/tests/test_certified_hex_browser_phase32.py')
bridge=importlib.util.module_from_spec(spec);spec.loader.exec_module(bridge)
def sha(x):return hashlib.sha256(json.dumps(x,sort_keys=True,separators=(',',':'),ensure_ascii=False).encode()).hexdigest()
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--count',type=int,default=4096)
    p.add_argument('--mode',choices=['golden','hash','spiral'],default='golden');p.add_argument('--pitches',default='0.50,1,3/2')
    a=p.parse_args();rows=[]
    for spelling in a.pitches.split(','):
        pair,source=parse_cell_scale_text(spelling)
        model=phase32.build(phase32.machine_config(a.count,a.mode),cell_pitch=pair,include_display=False)
        expected=model['cell_membership_exact'];phi=[None,*model['phase'][1:]]
        reply=bridge.invoke([{'op':'hashPhase32','args':[phi,*pair,{'includeCertificates':True}]}],timeout=300)[0]
        if not reply['ok']:raise AssertionError(reply)
        observed=reply['result'];tests={
          'summary_equal':observed['summary']=={k:v for k,v in expected.items() if k!='certificates'},
          'complete_certificates_equal':observed['certificates_sha256']==sha(expected['certificates']),
          'all_ordered_cells_equal':observed['cells_sha256']==sha([c['cell'] for c in expected['certificates']]),
          'full_record_equal':observed['full_record_sha256']==sha(expected)}
        if not all(tests.values()):raise AssertionError(tests)
        rows.append(dict(count=a.count,mode=a.mode,pitch=source,checks=tests,status=expected['status'],
                         occupied_positive_cells=expected['occupied_cells'],collision_excess=expected['collision_excess'],
                         unresolved=len(expected['unresolved_identities']),record_sha256=sha(expected),
                         certificates_sha256=observed['certificates_sha256']))
        print(json.dumps(rows[-1]),flush=True)
    rec=dict(schema='M20_PHASE32_BROWSER_POPULATION_V1',rows=rows,source='UNCHANGED_PYTHON_PHASE32_SCHEDULE',
             comparison='PYTHON_BRC_VS_NODE_BIGINT_FULL_RECORD',native_browser=False,finite_not_universal=True)
    out=ROOT/f'evidence/migration20/population_{a.count}_{a.mode}.json';out.write_text(json.dumps(rec,indent=2)+'\n')
if __name__=='__main__':main()
