"""Constructive Bezout access to the P025 absorption floor.

The scaled Wronskian image on the additive witness lattice is generated by the
2x2 minors of the primitive additive row and the raw Wronskian row.  A Bezout
identity among those minors therefore gives an explicit additive witness whose
Wronskian attains the exact positive image generator, hence ``eta_min``.

This is standard integer syzygy/Bezout algebra used as a certificate generator.
The project-specific point is to compare the resulting constructive radius with
the genuinely minimal absorption-access radius ``nu``.
"""

from __future__ import annotations

from dataclasses import dataclass

from .abc_witness_absorption import (
    arithmetic_wronskian_value,
    minimum_absorption_redundancy,
    multiplicity_residual_product,
    raw_wronskian_vector,
    witness_absorption_redundancy,
)
from .abc_witness_precision import additive_relation_vector, is_additive_witness


@dataclass(frozen=True)
class BezoutAbsorptionCertificate:
    """One explicit witness attaining the Wronskian image generator."""

    minors: tuple[int, ...]
    bezout_coefficients: tuple[int, ...]
    pair_indices: tuple[tuple[int, int], ...]
    witness: tuple[int, ...]
    image_generator: int
    absorption_redundancy: int
    radius: int
    triangle_radius_bound: int


def _extended_gcd(a: int, b: int) -> tuple[int, int, int]:
    """Return ``(g,x,y)`` with ``g>=0`` and ``a*x+b*y=g``."""
    if b == 0:
        if a >= 0:
            return a, 1, 0
        return -a, -1, 0
    g, x1, y1 = _extended_gcd(b, a % b)
    return g, y1, x1 - (a // b) * y1


def bezout_coefficients(values: tuple[int, ...]) -> tuple[int, tuple[int, ...]]:
    """Return a positive gcd and coefficients realizing it for nonzero values."""
    if not values or any(isinstance(value, bool) or not isinstance(value, int) for value in values):
        raise ValueError("values must be a nonempty tuple of integers")
    if all(value == 0 for value in values):
        raise ValueError("at least one value must be nonzero")

    first = values[0]
    if first >= 0:
        current_gcd = first
        coeffs = [1]
    else:
        current_gcd = -first
        coeffs = [-1]

    for value in values[1:]:
        g, x, y = _extended_gcd(current_gcd, value)
        coeffs = [x * coefficient for coefficient in coeffs] + [y]
        current_gcd = g

    if sum(value * coefficient for value, coefficient in zip(values, coeffs, strict=True)) != current_gcd:
        raise AssertionError("Bezout coefficient reconstruction failed")
    if current_gcd <= 0:
        raise AssertionError("nonzero integer list must have positive gcd")
    return current_gcd, tuple(coeffs)


def pair_syzygy(alpha: tuple[int, ...], i: int, j: int) -> tuple[int, ...]:
    """Return ``alpha_j e_i - alpha_i e_j`` in ``ker_Z(alpha)``."""
    if not (0 <= i < j < len(alpha)):
        raise ValueError("require 0 <= i < j < len(alpha)")
    vector = [0] * len(alpha)
    vector[i] = alpha[j]
    vector[j] = -alpha[i]
    result = tuple(vector)
    if sum(a * x for a, x in zip(alpha, result, strict=True)) != 0:
        raise AssertionError("pair syzygy escaped additive kernel")
    return result


def nonzero_wronskian_minors(
    a: int, b: int, c: int
) -> tuple[tuple[tuple[int, int], int], ...]:
    """Return all nonzero minors ``alpha_i*beta_j-alpha_j*beta_i``."""
    alpha = additive_relation_vector(a, b, c)
    beta = raw_wronskian_vector(a, b, c)
    entries: list[tuple[tuple[int, int], int]] = []
    for i in range(len(alpha)):
        for j in range(i + 1, len(alpha)):
            minor = alpha[i] * beta[j] - alpha[j] * beta[i]
            if minor:
                entries.append(((i, j), minor))
    if not entries:
        raise ValueError("Wronskian is degenerate on the additive witness lattice")
    return tuple(entries)


def bezout_absorption_certificate(a: int, b: int, c: int) -> BezoutAbsorptionCertificate:
    """Construct an explicit additive witness with ``eta=eta_min``.

    For each nonzero minor ``m_ij`` let

        t_ij = alpha_j e_i - alpha_i e_j.

    Then ``t_ij`` lies in ``ker(alpha)`` and ``beta·t_ij=-m_ij``.  If
    ``sum z_ij m_ij=d=gcd(m_ij)``, the witness

        x = -sum z_ij t_ij

    satisfies ``beta·x=d``.  Thus it attains the positive generator of the
    Wronskian image and therefore the exact minimum absorption redundancy.
    """
    alpha = additive_relation_vector(a, b, c)
    entries = nonzero_wronskian_minors(a, b, c)
    pairs = tuple(pair for pair, _minor in entries)
    minors = tuple(minor for _pair, minor in entries)
    image_generator, coefficients = bezout_coefficients(minors)

    witness = [0] * len(alpha)
    triangle_bound = 0
    for coefficient, (i, j) in zip(coefficients, pairs, strict=True):
        syzygy = pair_syzygy(alpha, i, j)
        for k, value in enumerate(syzygy):
            witness[k] -= coefficient * value
        triangle_bound += abs(coefficient) * max(abs(alpha[i]), abs(alpha[j]))

    witness_tuple = tuple(witness)
    if not is_additive_witness(a, b, c, witness_tuple):
        raise AssertionError("Bezout certificate escaped additive witness lattice")
    wronskian = arithmetic_wronskian_value(a, b, c, witness_tuple)
    if wronskian != image_generator:
        raise AssertionError("Bezout certificate failed to attain positive image generator")

    eta = witness_absorption_redundancy(a, b, c, witness_tuple)
    eta_floor = minimum_absorption_redundancy(a, b, c)
    if eta != eta_floor:
        raise AssertionError("Bezout certificate failed to attain eta_min")

    residual = multiplicity_residual_product(a, b, c)
    if image_generator != residual * eta_floor:
        raise AssertionError("image generator disagrees with residual times eta_min")

    radius = max(abs(value) for value in witness_tuple)
    if radius > triangle_bound:
        raise AssertionError("triangle radius bound failed")

    return BezoutAbsorptionCertificate(
        minors=minors,
        bezout_coefficients=coefficients,
        pair_indices=pairs,
        witness=witness_tuple,
        image_generator=image_generator,
        absorption_redundancy=eta,
        radius=radius,
        triangle_radius_bound=triangle_bound,
    )


def bezout_access_overhead(
    a: int,
    b: int,
    c: int,
    *,
    optimal_radius: int,
) -> dict[str, int | tuple[int, ...]]:
    """Compare the explicit Bezout certificate radius with a proved/known ``nu``.

    ``optimal_radius`` is supplied explicitly so this helper does not hide an
    expensive lattice search inside what is intended to be a constructive bound.
    """
    if isinstance(optimal_radius, bool) or not isinstance(optimal_radius, int) or optimal_radius <= 0:
        raise ValueError("optimal_radius must be a positive integer")
    certificate = bezout_absorption_certificate(a, b, c)
    if certificate.radius < optimal_radius:
        raise ValueError("optimal_radius cannot exceed the radius of an explicit floor witness")
    return {
        "witness": certificate.witness,
        "bezout_radius": certificate.radius,
        "optimal_radius": optimal_radius,
        "absolute_overhead": certificate.radius - optimal_radius,
        "triangle_radius_bound": certificate.triangle_radius_bound,
    }
