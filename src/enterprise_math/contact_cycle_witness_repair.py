"""Exact cycle-lattice witness repair for E001 contact impulse histories.

Let ``B`` be a signed body/contact incidence matrix and ``j in Z^E`` a
cumulative contact-impulse count.  The coarse body change is

    physical(j) = B j.

Let an additive future witness be

    witness(j) = C j

for an integer readout matrix ``C``.  Two impulse histories with the same coarse
body change differ by an integer cycle vector ``z in ker_Z B``.  Therefore the
witness is determined by the coarse body state exactly when

    ker_Z B subseteq ker_Z C.

For graph incidence matrices, ``ker_Z B`` is the integer cycle lattice
``H_1(G;Z)``.  A spanning forest supplies an exact fundamental-cycle Z-basis.
The hidden witness subgroup inside one physical fiber is therefore generated by

    C z_1, ..., C z_beta

for those fundamental cycles.  By the first isomorphism theorem it is exactly

    C(ker B) ~= ker B / (ker B intersect ker C).

This module exposes that contact-graph specialization constructively.  It does
not claim novelty for graph homology, kernel factorization or the first
isomorphism theorem.

The result sharpens the E001/P023 state boundary.  A tree has no cycle lattice,
so cumulative contact impulse is determined by body change.  Once cycles exist,
contact-local history can remain invisible to the coarse physical state.  A
future witness may erase those directions only when its readout kills them.
"""

from __future__ import annotations

from collections import deque
from dataclasses import dataclass
from fractions import Fraction
from math import gcd
from typing import Iterable, Sequence


Matrix = tuple[tuple[int, ...], ...]
Vector = tuple[int, ...]


def _require_int(name: str, value: int) -> None:
    if isinstance(value, bool) or not isinstance(value, int):
        raise TypeError(f"{name} must be an integer")


def _matrix(
    values: Sequence[Sequence[int]] | Iterable[Sequence[int]],
    *,
    name: str,
    column_count: int | None = None,
    require_nonempty_rows: bool = True,
) -> Matrix:
    rows = tuple(tuple(row) for row in values)
    if require_nonempty_rows and not rows:
        raise ValueError(f"{name} must contain at least one row")
    if rows:
        width = len(rows[0])
        if any(len(row) != width for row in rows):
            raise ValueError(f"{name} rows must have equal length")
    else:
        width = column_count if column_count is not None else 0
    if column_count is not None and width != column_count:
        raise ValueError(f"{name} must have {column_count} columns")
    for row in rows:
        for value in row:
            _require_int(name, value)
    return rows


def _incidence_matrix(
    values: Sequence[Sequence[int]] | Iterable[Sequence[int]],
) -> Matrix:
    rows = _matrix(values, name="incidence")
    edge_count = len(rows[0])
    for edge in range(edge_count):
        column = tuple(row[edge] for row in rows)
        if (
            column.count(-1) != 1
            or column.count(1) != 1
            or any(value not in (-1, 0, 1) for value in column)
        ):
            raise ValueError(
                "each incidence column must contain exactly one -1 and one +1"
            )
    return rows


def _vector(
    values: Sequence[int] | Iterable[int],
    length: int,
    *,
    name: str,
) -> Vector:
    result = tuple(values)
    if len(result) != length:
        raise ValueError(f"{name} must have length {length}")
    for value in result:
        _require_int(name, value)
    return result


def apply_integer_matrix(
    matrix: Sequence[Sequence[int]],
    vector: Sequence[int],
) -> Vector:
    rows = _matrix(matrix, name="matrix")
    values = _vector(vector, len(rows[0]), name="vector")
    return tuple(
        sum(entry * coordinate for entry, coordinate in zip(row, values, strict=True))
        for row in rows
    )


def _edge_endpoints(incidence: Matrix, edge: int) -> tuple[int, int]:
    source = next(
        body
        for body, row in enumerate(incidence)
        if row[edge] == -1
    )
    target = next(
        body
        for body, row in enumerate(incidence)
        if row[edge] == 1
    )
    return source, target


@dataclass(frozen=True)
class FundamentalCycleLattice:
    cycle_basis: tuple[Vector, ...]
    tree_edges: tuple[int, ...]
    chord_edges: tuple[int, ...]
    component_count: int

    @property
    def cycle_rank(self) -> int:
        return len(self.cycle_basis)


def fundamental_cycle_lattice(
    incidence: Sequence[Sequence[int]],
) -> FundamentalCycleLattice:
    """Construct a fundamental integer cycle basis from a spanning forest."""
    matrix = _incidence_matrix(incidence)
    body_count = len(matrix)
    edge_count = len(matrix[0])

    parent = list(range(body_count))
    rank = [0] * body_count

    def find(body: int) -> int:
        while parent[body] != body:
            parent[body] = parent[parent[body]]
            body = parent[body]
        return body

    def union(left: int, right: int) -> bool:
        left_root = find(left)
        right_root = find(right)
        if left_root == right_root:
            return False
        if rank[left_root] < rank[right_root]:
            left_root, right_root = right_root, left_root
        parent[right_root] = left_root
        if rank[left_root] == rank[right_root]:
            rank[left_root] += 1
        return True

    tree_edges: list[int] = []
    chord_edges: list[int] = []
    for edge in range(edge_count):
        source, target = _edge_endpoints(matrix, edge)
        if union(source, target):
            tree_edges.append(edge)
        else:
            chord_edges.append(edge)

    adjacency: list[list[tuple[int, int]]] = [
        [] for _ in range(body_count)
    ]
    for edge in tree_edges:
        source, target = _edge_endpoints(matrix, edge)
        adjacency[source].append((target, edge))
        adjacency[target].append((source, edge))

    basis: list[Vector] = []
    for chord in chord_edges:
        source, target = _edge_endpoints(matrix, chord)

        predecessor: dict[int, tuple[int | None, int | None]] = {
            target: (None, None)
        }
        queue: deque[int] = deque([target])
        while queue and source not in predecessor:
            current = queue.popleft()
            for neighbor, edge in adjacency[current]:
                if neighbor in predecessor:
                    continue
                predecessor[neighbor] = (current, edge)
                queue.append(neighbor)
        if source not in predecessor:
            raise AssertionError("chord endpoints were disconnected in the spanning forest")

        path: list[tuple[int, int, int]] = []
        current = source
        while current != target:
            previous, edge = predecessor[current]
            if previous is None or edge is None:
                raise AssertionError("tree path reconstruction terminated early")
            path.append((previous, current, edge))
            current = previous
        path.reverse()

        cycle = [0] * edge_count
        cycle[chord] = 1
        for path_source, path_target, edge in path:
            edge_source, edge_target = _edge_endpoints(matrix, edge)
            cycle[edge] = (
                1
                if (edge_source, edge_target)
                == (path_source, path_target)
                else -1
            )

        cycle_vector = tuple(cycle)
        if any(apply_integer_matrix(matrix, cycle_vector)):
            raise AssertionError("constructed fundamental cycle left the incidence kernel")
        basis.append(cycle_vector)

    component_count = len({find(body) for body in range(body_count)})
    expected_rank = edge_count - body_count + component_count
    if len(basis) != expected_rank:
        raise AssertionError("fundamental cycle count disagrees with E-N+c")

    return FundamentalCycleLattice(
        cycle_basis=tuple(basis),
        tree_edges=tuple(tree_edges),
        chord_edges=tuple(chord_edges),
        component_count=component_count,
    )


def decompose_incidence_cycle(
    incidence: Sequence[Sequence[int]],
    cycle_vector: Sequence[int],
) -> tuple[int, ...]:
    """Return exact integer coordinates in the fundamental cycle basis."""
    matrix = _incidence_matrix(incidence)
    edge_count = len(matrix[0])
    cycle = _vector(cycle_vector, edge_count, name="cycle_vector")
    if any(apply_integer_matrix(matrix, cycle)):
        raise ValueError("cycle_vector must lie in the incidence kernel")

    lattice = fundamental_cycle_lattice(matrix)
    coefficients = tuple(cycle[edge] for edge in lattice.chord_edges)
    reconstructed = tuple(
        sum(
            coefficient * basis_vector[index]
            for coefficient, basis_vector in zip(
                coefficients,
                lattice.cycle_basis,
                strict=True,
            )
        )
        for index in range(edge_count)
    )
    if reconstructed != cycle:
        raise AssertionError("fundamental cycles failed to reconstruct an integer kernel vector")
    return coefficients


def _rational_row_rank(vectors: Sequence[Vector]) -> int:
    rows = [
        [Fraction(value) for value in vector]
        for vector in vectors
        if any(vector)
    ]
    if not rows:
        return 0

    row_count = len(rows)
    column_count = len(rows[0])
    pivot_row = 0
    pivot_column = 0
    while pivot_row < row_count and pivot_column < column_count:
        pivot = next(
            (
                index
                for index in range(pivot_row, row_count)
                if rows[index][pivot_column] != 0
            ),
            None,
        )
        if pivot is None:
            pivot_column += 1
            continue

        rows[pivot_row], rows[pivot] = rows[pivot], rows[pivot_row]
        pivot_value = rows[pivot_row][pivot_column]
        rows[pivot_row] = [
            value / pivot_value
            for value in rows[pivot_row]
        ]
        for index in range(row_count):
            if index == pivot_row:
                continue
            factor = rows[index][pivot_column]
            if factor == 0:
                continue
            rows[index] = [
                left - factor * right
                for left, right in zip(
                    rows[index],
                    rows[pivot_row],
                    strict=True,
                )
            ]
        pivot_row += 1
        pivot_column += 1
    return pivot_row


@dataclass(frozen=True)
class ContactCycleWitnessRepairReport:
    cycle_rank: int
    hidden_witness_rank: int
    witness_descends_through_body_state: bool
    cycle_basis: tuple[Vector, ...]
    hidden_witness_generators: tuple[Vector, ...]
    scalar_hidden_grain: int | None

    @property
    def hidden_witness_present(self) -> bool:
        return self.hidden_witness_rank > 0


def contact_cycle_witness_repair_report(
    incidence: Sequence[Sequence[int]],
    witness_matrix: Sequence[Sequence[int]],
) -> ContactCycleWitnessRepairReport:
    """Compile the exact hidden witness image of the contact cycle lattice."""
    body_incidence = _incidence_matrix(incidence)
    edge_count = len(body_incidence[0])
    witness = _matrix(
        witness_matrix,
        name="witness_matrix",
        column_count=edge_count,
    )
    lattice = fundamental_cycle_lattice(body_incidence)

    hidden_generators = tuple(
        apply_integer_matrix(witness, cycle)
        for cycle in lattice.cycle_basis
    )
    hidden_rank = _rational_row_rank(hidden_generators)
    descends = all(not any(generator) for generator in hidden_generators)

    scalar_grain: int | None
    if len(witness) == 1:
        scalar_grain = 0
        for generator in hidden_generators:
            scalar_grain = gcd(
                scalar_grain,
                abs(generator[0]),
            )
    else:
        scalar_grain = None

    return ContactCycleWitnessRepairReport(
        cycle_rank=lattice.cycle_rank,
        hidden_witness_rank=hidden_rank,
        witness_descends_through_body_state=descends,
        cycle_basis=lattice.cycle_basis,
        hidden_witness_generators=hidden_generators,
        scalar_hidden_grain=scalar_grain,
    )


def same_body_delta(
    incidence: Sequence[Sequence[int]],
    left_impulse: Sequence[int],
    right_impulse: Sequence[int],
) -> bool:
    """Whether two impulse histories induce the same coarse body change."""
    matrix = _incidence_matrix(incidence)
    edge_count = len(matrix[0])
    left = _vector(left_impulse, edge_count, name="left_impulse")
    right = _vector(right_impulse, edge_count, name="right_impulse")
    return apply_integer_matrix(matrix, left) == apply_integer_matrix(
        matrix,
        right,
    )


def same_witness_readout(
    witness_matrix: Sequence[Sequence[int]],
    left_impulse: Sequence[int],
    right_impulse: Sequence[int],
) -> bool:
    """Whether two impulse histories have the same declared additive witness."""
    left = tuple(left_impulse)
    right = tuple(right_impulse)
    if len(left) != len(right):
        raise ValueError("impulse vectors must have equal length")
    witness = _matrix(
        witness_matrix,
        name="witness_matrix",
        column_count=len(left),
    )
    left_values = _vector(left, len(left), name="left_impulse")
    right_values = _vector(right, len(left), name="right_impulse")
    return apply_integer_matrix(witness, left_values) == apply_integer_matrix(
        witness,
        right_values,
    )
