"""Causal dimension as the rank revealed by graded event generators.

For a graded finite event family define L_R as the integer subgroup generated by
all allowed events of grade at most R.  Its free rank is the causal displacement
dimension visible at that grade.  The rank is monotone nondecreasing as more event
channels are revealed.

For total mod-m conservation with unit-amplitude/support grade:

* m=1: support-one axis events reveal rank N immediately;
* m=2: support-two D events reveal rank N immediately;
* m>=3: support-two A transfers reveal rank N-1; the first support-m all-plus or
  all-minus modular event adds one independent total-changing direction, raising
  the full rank to N.

Thus a mod-m world can have an A_(N-1) primitive geometry yet a full causal event
rank N.  Dimension is therefore a graded operational shadow, not necessarily a
single primitive coordinate count.
"""

from __future__ import annotations

from fractions import Fraction

from .causal_conservation_tomography import unit_amplitude_events, modular_total_law

Vector = tuple[int, ...]


def rational_rank(vectors: tuple[Vector, ...]) -> int:
    if not vectors:
        return 0
    width = len(vectors[0])
    if any(len(vector) != width for vector in vectors):
        raise ValueError("vectors must have equal width")
    matrix = [[Fraction(value) for value in vector] for vector in vectors]
    row = 0
    for column in range(width):
        pivot = next(
            (candidate for candidate in range(row, len(matrix)) if matrix[candidate][column] != 0),
            None,
        )
        if pivot is None:
            continue
        matrix[row], matrix[pivot] = matrix[pivot], matrix[row]
        pivot_value = matrix[row][column]
        matrix[row] = [value / pivot_value for value in matrix[row]]
        for other in range(len(matrix)):
            if other == row:
                continue
            factor = matrix[other][column]
            if factor != 0:
                matrix[other] = [
                    value - factor * pivot_entry
                    for value, pivot_entry in zip(matrix[other], matrix[row])
                ]
        row += 1
        if row == len(matrix):
            break
    return row


def support_grade(event: Vector) -> int:
    return sum(value != 0 for value in event)


def event_rank_through_grade(
    universe: tuple[Vector, ...],
    law,
    grade,
    budget: int,
) -> int:
    if budget < 0:
        raise ValueError("budget must be non-negative")
    events = tuple(
        event
        for event in universe
        if law(event) and grade(event) <= budget
    )
    return rational_rank(events)


def dimension_profile(
    universe: tuple[Vector, ...],
    law,
    grade,
    maximum_budget: int,
) -> tuple[int, ...]:
    return tuple(
        event_rank_through_grade(universe, law, grade, budget)
        for budget in range(maximum_budget + 1)
    )


def dimension_revelation_spectrum(profile: tuple[int, ...]) -> tuple[int, ...]:
    if not profile:
        return ()
    previous = 0
    increments = []
    for rank in profile:
        if rank < previous:
            raise ValueError("dimension profile must be nondecreasing")
        increments.append(rank - previous)
        previous = rank
    return tuple(increments)


def modular_unit_dimension_profile(slot_count: int, modulus: int) -> tuple[int, ...]:
    if slot_count < 1 or modulus < 1:
        raise ValueError("slot count and modulus must be positive")
    universe = unit_amplitude_events(slot_count)
    maximum = min(slot_count, max(2, modulus))
    return dimension_profile(
        universe,
        modular_total_law(modulus),
        support_grade,
        maximum,
    )
