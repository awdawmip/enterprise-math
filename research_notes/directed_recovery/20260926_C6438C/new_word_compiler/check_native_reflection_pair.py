"""Actual full-carrier native words for a rational infinite-order rotation.

Every certified basis column is generated by the frozen apply_word executor.
Fraction algebra below only observes those columns and verifies identities.
No numerical trigonometry, target refinement, or Shor propagation is used.
"""
