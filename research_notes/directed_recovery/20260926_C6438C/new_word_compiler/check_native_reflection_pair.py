DIM = 61


def packed(value):
    return json.dumps(encode(value), ensure_ascii=False, sort_keys=True,
                      separators=(',', ':')).encode('utf-8')


def basis(index):
    return [int(i == index) for i in range(DIM)]


def dot(left, right):
    return sum((a*b for a, b in zip(left, right) if a and b), F(0))


def rational_vector(numerators, denominator):
    return tuple(F(x, denominator) for x in numerators)


def linear_combination(left, alpha, right, beta):
    return tuple(alpha*a + beta*b for a, b in zip(left, right))


def check_word(name, word):
    columns = []
    vectors = []
    for j in range(DIM):
        start = basis(j)
        numerators, denominator = fixed.apply_word(start, 1, word)
        recovered, recovered_denominator = fixed.apply_word(
            numerators, denominator, word, inverse=True)
        assert recovered == start and recovered_denominator == 1
        columns.append({'source': j, 'numerators': numerators,
                        'denominator': denominator,
                        'inverse_recovered_numerators': recovered,
                        'inverse_recovered_denominator': recovered_denominator})
        vectors.append(rational_vector(numerators, denominator))
    gram = [[dot(left, right) for right in vectors] for left in vectors]
    assert all(gram[i][j] == int(i == j)
               for i in range(DIM) for j in range(DIM))
    untouched = []
    for j, vector in enumerate(vectors):
        if vector == tuple(basis(j)):
            untouched.append(j)
    return {'name': name, 'temporal_word': word,
            'complete_basis_columns': columns,
            'complete_gram_matrix': gram,
            'orthogonal_on_all_columns': True,
            'full_inverse_recovery': True,
            'fixed_standard_basis_indices': untouched,
            'primitive_counts': {kind: sum(g[0] == kind for g in word)
                                 for kind in ('h4', 'neg', 'swap')}}, vectors


def source_record(path):
    path = Path(path).resolve()
    return {'path': str(path),
            'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}


def build(activity):
    started = perf_counter_ns()
    vendor = verify_vendor()
    first_call = len(CALLS)
    primitive_receipt = fixed.primitives()
    h_w = (('h4', 0, 1, 2, 3),)
    h_v = (('h4', 0, 1, 2, 4),)
    neg_zero = (('neg', 0),)
    swap_34 = (('swap', 3, 4),)
    H_w = h_w + neg_zero + h_w
    H_v = h_v + neg_zero + h_v
    # Matrix G=H_w H_v means that H_v is executed first.
    G = H_v + H_w
    G_inverse = H_w + H_v
    words = {'h4_w': h_w, 'h4_v': h_v, 'neg_zero': neg_zero,
             'swap_34': swap_34, 'H_w': H_w, 'H_v': H_v,
             'G_Hw_Hv': G, 'G_inverse_Hv_Hw': G_inverse}
    records, actual_columns = {}, {}
    for name, word in words.items():
        records[name], actual_columns[name] = check_word(name, word)

    # Normals are obtained from the actual H4 columns, not entered as new
    # transformations. Their simple coordinate descriptions are checked below.
    w = actual_columns['h4_w'][0]
    v = actual_columns['h4_v'][0]
    assert w == tuple(F(int(i in (0, 1, 2, 3)), 2) for i in range(DIM))
    assert v == tuple(F(int(i in (0, 1, 2, 4)), 2) for i in range(DIM))
    assert dot(w, w) == dot(v, v) == 1
    c = dot(w, v)
    assert c == F(3, 4)
    for j in range(DIM):
        e_j = tuple(basis(j))
        assert actual_columns['H_w'][j] == linear_combination(e_j, 1, w, -2*w[j])
        assert actual_columns['H_v'][j] == linear_combination(e_j, 1, v, -2*v[j])
        # The second support is also an actual routing conjugate of the first.
        routed_n, routed_d = fixed.apply_word(basis(j), 1, swap_34 + h_w + swap_34)
        assert rational_vector(routed_n, routed_d) == actual_columns['h4_v'][j]
        # Explicit positive word for G inverse agrees with inverse execution.
        inverse_n, inverse_d = fixed.apply_word(basis(j), 1, G, inverse=True)
        assert rational_vector(inverse_n, inverse_d) == actual_columns['G_inverse_Hv_Hw'][j]
    assert all(j in records[name]['fixed_standard_basis_indices']
               for name in ('H_w', 'H_v', 'G_Hw_Hv', 'G_inverse_Hv_Hw')
               for j in range(5, DIM))

    plane_runs = []
    for name, vector, expected in (
        ('w', w, linear_combination(w, F(5, 4), v, F(-3, 2))),
        ('v', v, linear_combination(w, F(3, 2), v, F(-1)))):
        numerators = [int(2*x) for x in vector]
        actual_n, actual_d = fixed.apply_word(numerators, 2, G)
        actual = rational_vector(actual_n, actual_d)
        assert actual == expected
        plane_runs.append({'input_name': name, 'input_numerators': numerators,
                           'input_denominator': 2, 'actual_numerators': actual_n,
                           'actual_denominator': actual_d})

    # A full rational basis of span(w,v)^perp, including its three directions
    # inside the first five coordinates. All 59 are executed as actual words.
    complement = []
    for positions in ((0, 1), (0, 2)):
        row = basis(positions[0]); row[positions[1]] = -1
        complement.append(row)
    row = basis(0); row[3] = row[4] = -1
    complement.append(row)
    complement.extend(basis(j) for j in range(5, DIM))
    complement_runs = []
    for row in complement:
        assert dot(row, w) == dot(row, v) == 0
        actual_n, actual_d = fixed.apply_word(row, 1, G)
        assert actual_n == row and actual_d == 1
        complement_runs.append({'input': row, 'actual_numerators': actual_n,
                                'actual_denominator': actual_d})
    assert len(complement) == DIM - 2
    # Independence: e0-e1, e0-e2, e0-e3-e4 have separate nonzero coordinates
    # 1,2,3; the remaining basis vectors have separate coordinates >=5.

    matrix_in_w_v = ((F(5, 4), F(3, 2)), (F(-3, 2), F(-1)))
    active_trace = matrix_in_w_v[0][0] + matrix_in_w_v[1][1]
    active_det = (matrix_in_w_v[0][0]*matrix_in_w_v[1][1]
                  - matrix_in_w_v[0][1]*matrix_in_w_v[1][0])
    assert active_trace == F(1, 4) and active_det == 1
    gram_det = 1 - c*c
    cosine = active_trace/2
    sine_square = 1 - cosine*cosine
    assert gram_det == F(7, 16) and cosine == F(1, 8)
    assert sine_square == F(63, 64)
    assert sum(actual_columns['G_Hw_Hv'][j][j] for j in range(DIM)) == DIM-2+active_trace

    return {
        'schema': 'BRC_NATIVE_REFLECTION_PAIR_FULL_CARRIER_V1',
        'activity': activity,
        'status': 'AUTHOR_EXECUTED_FINITE_WORD_BINDING_UNREVIEWED_NOT_ADMITTED',
        'global_knowledge_canonical': '441ebefd3ba2372abf9044d802fa816b4c4ef895',
        'registration_source': 'f0e5fb6f478a5a380ab5a7533d2585f7f43ee3bf',
        'frozen_stage87_source_head': '0852cad130c1d877174d235687cf60c19f318c58',
        'internal_dimension': DIM, 'vendor': vendor,
        'native_primitive_receipt': primitive_receipt,
        'actual_BRC_core_calls': len(CALLS)-first_call,
        'native_call_receipts': CALLS[first_call:],
        'words': records, 'w': w, 'v': v,
        'reflection_identity_all_61_columns_verified': True,
        'support_routing_swap_conjugacy_all_61_columns_verified': True,
        'normal_gram': ((F(1), c), (c, F(1))),
        'normal_gram_determinant': gram_det,
        'actual_plane_vector_runs': plane_runs,
        'matrix_G_in_nonorthogonal_basis_w_v': matrix_in_w_v,
        'plane_trace': active_trace, 'plane_determinant': active_det,
        'plane_cosine': cosine, 'plane_sine_squared': sine_square,
        'plane_characteristic_polynomial_coefficients': [F(1), F(-1, 4), F(1)],
        'complement_basis_dimension': len(complement),
        'actual_complement_vector_runs': complement_runs,
        'determinants_by_reflection_and_complement': {'H_w': -1, 'H_v': -1, 'G': 1},
        'observed_full_trace_G': DIM-2+active_trace,
        'resource_counts': {'distinct_complete_words': len(words),
            'forward_complete_basis_columns': DIM*len(words),
            'inverse_recovered_complete_basis_columns': DIM*len(words),
            'Gram_entries_checked': DIM*DIM*len(words),
            'routing_conjugacy_columns': DIM,
            'explicit_inverse_word_comparison_columns': DIM,
            'executed_plane_vectors': 2,
            'executed_fixed_complement_vectors': len(complement)},
        'source_files': [source_record(__file__), source_record(fixed.__file__)],
        'numerical_trigonometry_or_pi_used': False,
        'ordinary_float_propagation_used': False,
        'target32_vector64_bank_changed': False,
        'higher_precision_compilation_run': False,
        'large_word_enumeration_run': False,
        'claim_scope': 'exact native finite-word full-carrier binding and rational plane identities; no target compiler implementation or accuracy guarantee',
        'elapsed_ns': perf_counter_ns()-started}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--activity', required=True)
    args = parser.parse_args()
    certificate = build(args.activity)
    raw = packed(certificate)
    destination = ROOT / 'NATIVE_REFLECTION_PAIR_CERTIFICATE.json.gz'
    temporary = destination.with_suffix(destination.suffix+'.tmp')
    temporary.write_bytes(gzip.compress(raw, mtime=0))
    temporary.replace(destination)
    assert gzip.decompress(destination.read_bytes()) == raw
    print(json.dumps({'file': str(destination),
        'payload_sha256': hashlib.sha256(raw).hexdigest(),
        'compressed_bytes': destination.stat().st_size,
        'uncompressed_bytes': len(raw),
        'actual_BRC_core_calls': certificate['actual_BRC_core_calls'],
        'plane_cosine': str(certificate['plane_cosine']),
        'resource_counts': certificate['resource_counts']}), flush=True)


if __name__ == '__main__':
    main()
