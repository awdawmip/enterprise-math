#!/usr/bin/env python3
"""EC49BV: exact signed-X6 positive-branch BRC orbit/filter rank via multiset DP.

Carrier: ordered 12-letter signed native X6 words with fixed endpoint and length.
Observer: first/last signed steps; a finite Boolean algebra generated by declared
contiguous-pattern filters, after each axis permutation in H; fixed or covariant
positive-rational instrumentation. All arithmetic is exact. Author-side only.
"""
from __future__ import annotations
from collections import defaultdict
from fractions import Fraction
from functools import lru_cache
from itertools import permutations
from math import factorial
import json
import sys
from pathlib import Path

from signed_brc import endpoint_multiplicity, endpoint_weight

SIX=(0,0,0,0,0,0)
WP=(2,3,3,2,1,1)
WM=(1,1,1,1,1,1)
ID=tuple(range(6)); SWAP=(1,0,2,3,4,5)
PATTERNS=((0,1),(1,0))  # +E1,+E2 and +E2,+E1 (zero-indexed)


def compositions(total, slots):
    if slots==1:
        yield (total,)
    else:
        for a in range(total+1):
            for tail in compositions(total-a,slots-1):
                yield (a,)+tail


def validate_group_patterns(H, patterns):
    assert H and len(set(H))==len(H) and ID in H
    assert all(len(h)==6 and set(h)==set(range(6)) for h in H)
    assert all(tuple(a[b] for b in h) in H for a in H for h in H)
    assert patterns and all(p and all(0<=s<12 for s in p) for p in patterns)
    assert len(set(patterns))==len(patterns)


def signature_patterns(H, patterns):
    validate_group_patterns(H,patterns)
    # Pattern occurrence in h(word) equals occurrence of inverse-h(pattern)
    inv_patterns={}
    for h in H:
        inv=tuple(h.index(i) for i in range(6))
        for pat in patterns:
            original=tuple(inv[s] if s<6 else inv[s-6]+6 for s in pat)
            inv_patterns[original]=inv_patterns.get(original,0)|(1 << (H.index(h)*len(patterns)+patterns.index(pat)))
    return inv_patterns


def attainable_atoms(k, H=(ID,SWAP), patterns=PATTERNS):
    # Each +axis and -axis appears k_i times; never iterate all permutations of a word.
    counts0=k+k
    pat_map=signature_patterns(H, patterns)
    lookback=max((len(x) for x in pat_map),default=1)-1
    @lru_cache(None)
    def suffixes(rem, prev, mask):
        if not any(rem):
            return frozenset(((prev[-1], mask),))
        results=set()
        for a,num in enumerate(rem):
            if not num:
                continue
            rem2=list(rem);rem2[a]-=1
            nxt=prev+(a,)
            m=mask
            for pattern,bits in pat_map.items():
                if len(nxt)>=len(pattern) and nxt[-len(pattern):]==pattern:
                    m |= bits
            results.update(suffixes(tuple(rem2),nxt[-lookback:] if lookback else (a,),m))
        return frozenset(results)
    atoms=set()
    for first,num in enumerate(counts0):
        if not num: continue
        rem=list(counts0);rem[first]-=1
        initial_mask=0
        for pat,bits in pat_map.items():
            if pat==(first,):initial_mask |= bits
        for last,mask in suffixes(tuple(rem),(first,),initial_mask):
            atoms.add((first,last,mask))
    info={"cache_states":suffixes.cache_info().currsize,"atoms":len(atoms)}
    suffixes.cache_clear()
    return atoms,info


def rank_of_columns(columns):
    # Incremental exact row-echelon basis: number of linearly independent columns.
    pivots={}
    for col in columns:
        v=[Fraction(c) for c in col]
        for p,b in sorted(pivots.items()):
            if v[p]:
                factor=v[p]
                v=[x-factor*y for x,y in zip(v,b)]
        nxt=next((i for i,x in enumerate(v) if x),None)
        if nxt is not None:
            scale=v[nxt]
            pivots[nxt]=tuple(x/scale for x in v)
    return len(pivots)


def orbit(k,H,wp,wm,covariant=False):
    q=[Fraction(a)*Fraction(b) for a,b in zip(wp,wm)]
    if covariant:
        t=__import__('math').prod(q[i]**k[i] for i in range(6))
        return tuple([t]*len(H))
    return tuple(__import__('math').prod(q[h[i]]**k[i] for i in range(6)) for h in H)


def analyze(n, H=(ID,SWAP), patterns=PATTERNS,wp=WP,wm=WM):
    assert n%2==0 and n>=2
    atoms=defaultdict(list)
    states=0; ks=0
    for k in compositions(n//2,6):
        ks+=1
        current,info=attainable_atoms(k,H,patterns)
        states+=info['cache_states']
        for atom in current:
            atoms[atom].append(k)
    raw=0; sep=0; total=0; count_added=False
    rank_hist={}
    for atom,values in atoms.items():
        original_mask=atom[2]&((1<<len(patterns))-1)
        # base first/last always retained. Boolean algebra has four atoms.
        columns=[orbit(k,H,wp,wm) for k in values]
        rr=rank_of_columns(columns)
        total+=rr; rank_hist[rr]=rank_hist.get(rr,0)+1
        if rank_of_columns([c+(Fraction(1),) for c in columns])>rr:
            count_added=True
        # 'separate A and B' observation is not a full atom decomposition,
        # so it is deliberately not computed by simply summing atom ranks.
    w=endpoint_weight(n,SIX,wp,wm)
    m=endpoint_multiplicity(n,SIX)
    predicted_m=0; predicted_w=Fraction(0)
    for k in compositions(n//2,6):
        denom=__import__('math').prod(factorial(a)**2 for a in k)
        mult=factorial(n)//denom
        predicted_m+=mult
        predicted_w+=mult*orbit(k,(ID,),wp,wm)[0]
    assert m==predicted_m and w==predicted_w
    # Covariant action: weights co-transport, columns become constant across H.
    covariant=sum(rank_of_columns([orbit(k,H,wp,wm,True) for k in values]) for values in atoms.values())
    return {"n":n,"exact_closed_words":m,"native_endpoint_weight":str(w),"signed_histogram_classes":ks,
            "realizable_filter_atoms":len(atoms),"fixed_instrument_rank":total,"covariant_instrument_rank":covariant,
            "count_coordinate_extra":int(count_added),"rank_profile":rank_hist,
            "memoized_tail_states_summed":states,"no_raw_word_enumeration":True}


def test_rank():
    assert rank_of_columns([(2,3),(4,6),(3,2)])==2
    assert rank_of_columns([(2,3),(4,6)])==1
    assert rank_of_columns([(0,0),(0,0)])==0


def main():
    test_rank()
    lengths=[int(x) for x in sys.argv[1:]] or [4,6,8,10]
    out={"schema":"EC49BV_EXACT_MULTISETS_V1","native_source_git_blob":"300a96e3dc24bf6fff73743037a0347a8bc83176",
         "H":[list(ID),list(SWAP)],"weights_positive":list(WP),"weights_negative":list(WM),
         "filters":[list(x) for x in PATTERNS],"models":[]}
    for n in lengths:
        data=analyze(n)
        print(json.dumps(data,sort_keys=True),flush=True)
        out['models'].append(data)
    p=Path(__file__).with_name('EXACT_REPORT_EC49BV.json')
    p.write_text(json.dumps(out,ensure_ascii=False,indent=2,sort_keys=True)+"\n",encoding='utf-8')
    print(f"EXACT_EC49BV_PASS report={p}")

if __name__=='__main__':
    main()
