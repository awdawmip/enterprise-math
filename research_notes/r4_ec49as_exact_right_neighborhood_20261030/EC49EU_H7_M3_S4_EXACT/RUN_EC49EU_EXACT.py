#!/usr/bin/env python3
"""Generate all three exhaustive native-prefix tries and run exact C++ OR-mask DP.
All input words and the finite cache-key assignments are generated by the
standalone Python model. No optimization solver is used for the lower bounds.
"""
import hashlib,json,re,subprocess
from pathlib import Path
from VERIFY_EC49EU_M3S4 import assignments,case_word_map,make_milp

ROOT=Path(__file__).resolve().parent
CPP=ROOT/'VERIFY_EC49EU_EXACT_DP.cpp'
EXE=ROOT/'verify_ec49eu_exact'
EXPECTED=[116,116,128]

def run():
  subprocess.run(['g++','-O3','-std=c++17',str(CPP),'-o',str(EXE)],check=True)
  report={'unit':'EC49EU','status':'PASS','proof_kernel':'exact finite rooted native signed-step prefix trie OR-mask dynamic programming','max_cover_bits':20,'base_edges':28,'cases':[]}
  for i,ps in enumerate(assignments(),1):
    m=make_milp(case_word_map(ps)); masks=[0]*len(m['prefixes'])
    for bit,ends in m['colors'].items():
      for v in ends:masks[v]|=1<<bit
    inp=ROOT/f'EC49EU_H7_M3S4_CASE{i}_TRIE.txt'
    txt=f'{len(masks)} 20\n'+''.join(f'{m["parent"][j]} {int(j in m["base"])} {x}\n' for j,x in enumerate(masks))
    inp.write_text(txt)
    res=subprocess.run([str(EXE)],input=txt,text=True,capture_output=True,check=True)
    line=res.stdout.strip()
    mt=re.fullmatch(r'PASS min_extra=(\d+) total=(\d+) nodes=(\d+) colors=(\d+) largest_states=(\d+) convolutions=(\d+)',line)
    assert mt is not None,(i,line)
    extra,total,nodes,bits,largest,convolutions=map(int,mt.groups())
    assert total==EXPECTED[i-1] and extra==total-28
    assert nodes==len(masks) and bits==20
    report['cases'].append({'case':i,'p_h3_to_h7':[list(p) for p in ps], 'terminal_signature_bits':bits,'all_eligible_trie_nodes':nodes,'exact_extra_edges':extra,'exact_total_edges':total,'largest_DP_states':largest,'integer_convolutions':convolutions,'trie_input_sha256':hashlib.sha256(txt.encode()).hexdigest(), 'exact_run_stdout':line})
  return report

if __name__=='__main__':
  r=run();(ROOT/'EC49EU_EXACT_EXECUTED.json').write_text(json.dumps(r,indent=2)+'\n')
  print(json.dumps({'status':r['status'],'exact_minima':[x['exact_total_edges'] for x in r['cases']],'nodes':[x['all_eligible_trie_nodes'] for x in r['cases']]},indent=2))
