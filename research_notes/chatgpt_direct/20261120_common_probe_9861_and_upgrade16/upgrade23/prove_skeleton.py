def hungarian(cost):
 """Minimum cost injection of rows into columns, with exact integer duals."""
 n,m=len(cost),len(cost[0]);assert n<=m
 u=[0]*(n+1);v=[0]*(m+1);p=[0]*(m+1);way=[0]*(m+1)
 for i in range(1,n+1):
  p[0]=i;j0=0;minimum=[10**9]*(m+1);used=[False]*(m+1)
  while True:
   used[j0]=True;i0=p[j0];delta=10**9;j1=0
   for j in range(1,m+1):
    if not used[j]:
     cur=cost[i0-1][j-1]-u[i0]-v[j]
     if cur<minimum[j]:minimum[j]=cur;way[j]=j0
     if minimum[j]<delta:delta=minimum[j];j1=j
   for j in range(m+1):
    if used[j]:u[p[j]]+=delta;v[j]-=delta
    else:minimum[j]-=delta
   j0=j1
   if p[j0]==0:break
  while True:
   j1=way[j0];p[j0]=p[j1];j0=j1
   if j0==0:break
