"""Fresh-ID selection by conservative low-bit partitioning.

Production reads only complete Boolean registers generated by the inherited
BRC kernel.  It neither decodes request rows nor assumes their current validity.
Slot lists and candidate prefixes are explicit temporary controller state.
"""
from __future__ import annotations
from functools import lru_cache
from itertools import product
from pathlib import Path
import argparse, hashlib, json, sys
ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT/'parent'))
import check_addressed as prior
base,p,m,e,r=prior.base,prior.p,prior.m,prior.e,prior.r
ONE,ZERO=prior.ONE,prior.ZERO
CHECKS=0

def ck(ok, message):
    global CHECKS
    CHECKS += 1
    if not ok: raise AssertionError(message)


class Compiler(prior.Compiler):
    def __init__(self,H=base.H_DEFAULT,slots=2,index_start=None):
        super().__init__(H=H,slots=slots,index_start=index_start)
        oldH=self.H
        self.H=set(self.H)
        self.conflicts=tuple(tuple(s for s,g in enumerate(self.targets)
                                   if set(g)&set(h)) for h in self.targets)
        self.free_reads={}
        self.create_words={}
        self.children={}
        self.leaf_color={}
        for t in range(self.d):
            w=self.clearout()
            for s in self.conflicts[t]:
                w+=self.emit_write((self.current[s].anchor,),self.marker)
            w+=self.emit_read(self.marker[0],invert=True)+[p.one(self.marker[1])]
            self.free_reads[t]=tuple(w)
            # Static binary trie of consecutive legal keys, least-significant bit first.
            def make(k,prefix,colors):
                self.leaf_color[t,k,prefix]=min(colors)
                if k==self.color_bits: return
                groups=tuple(tuple(c for c in colors if (self.key(t,c)>>k)&1==bit)
                             for bit in (0,1))
                self.children[t,k,prefix]=tuple(len(g) for g in groups)
                for bit,g in enumerate(groups):
                    if g:make(k+1,prefix|(bit<<k),g)
            make(0,0,tuple(range(self.colors)))
            for c in range(self.colors):
                code=self.key(t,c)
                for last in (0,1):
                    w=self.clear_shared(t)
                    w += [p.add(self.current[t].cell(c)),p.add(self.targets[t])]
                    w += [p.add(self.shared[t][b]) for b in range(self.bits) if code>>b&1]
                    if not last:
                        w += self.clearout()+[p.add(h) for h in p.reg(self.out,1)]
                    self.create_words[t,c,last]=tuple(w)
        self.H=frozenset(self.H)
        self.new_candidates=self.H-oldH
        self._raw=lru_cache(maxsize=500000)(self._uncached)
        self.calls=self.uses=0

    def branch(self,t,k,prefix,groups):
        """Pure finite control: capacities are compile-time facts, counts are observations."""
        caps=self.children[t,k,prefix]
        eligible=[bit for bit in (0,1) if len(groups[bit])<caps[bit]]
        if not eligible:raise ValueError('Vacancy invariant violated')
        bit=min(eligible,key=lambda s:(len(groups[s]),s))
        return bit,groups[bit],caps

    def allocate(self,J,t,trace=False,repeats=1,omitted=(),slot_subset=None):
        if not 0<=t<self.d or repeats<1:raise ValueError('Invalid allocation arguments')
        # slot_subset is only an explicit fault-injection seam; normal calls use every slot.
        active=tuple(range(self.slots)) if slot_subset is None else tuple(slot_subset)
        words=[];logs=[];observations=[];levels=[];mass=e.prep(J);omitted=set(omitted)
        def do(block):
            nonlocal J,mass
            start=len(words);ww=tuple(raw for raw in block for _ in range(repeats))
            drops={j-start for j in omitted if start<=j<start+len(ww)}
            J,wm,ll=self.runword(J,ww,trace,drops)
            mass=r.serial(mass,wm)
            if trace:ll=[dict(x,position=x['position']+start) for x in ll]
            words.extend(ww);logs.extend(ll)
        do(self.free_reads[t]);available=bool(self.observe_result(J))
        observations.append(('target_available',t,int(available)))
        if not available:
            return J,mass,dict(word=tuple(words),trace=logs,commands=len(words),read_bits=0,
                               observations=observations,levels=[],color=None,key=None)
        k=prefix=reads=0;last=1
        while active:
            before=active;groups=[[],[]]
            for i in active:
                do(self.reads[i,k]);last=int(self.observe_result(J));reads+=1
                observations.append(('request_key_bit',i,k,last));groups[last].append(i)
            groups=tuple(tuple(g) for g in groups)
            bit,active,caps=self.branch(t,k,prefix,groups)
            levels.append(dict(bit_position=k,prefix=prefix,active_slots=before,
                               candidate_counts=caps,blocker_counts=tuple(map(len,groups)),
                               selected_bit=bit,remaining_slots=active))
            prefix|=bit<<k;k+=1
        c=self.leaf_color[t,k,prefix]
        do(self.create_words[t,c,last])
        return J,mass,dict(word=tuple(words),trace=logs,commands=len(words),read_bits=reads,
                           observations=observations,levels=levels,color=c,key=self.key(t,c),last=last)

    def run(self,J,op,trace=False):
        if op[0]=='reserve':
            K,wm,data=self.allocate(J,op[1],trace)
            return K,wm,data['trace']
        return super().run(J,op,trace)

    def metrics(self):
        return dict(assertions=CHECKS,slots=self.slots,targets=self.d,colors=self.colors,
                    bits=self.bits,color_bits=self.color_bits,members=self.members,
                    candidates=len(self.H),new_candidates=len(self.new_candidates),
                    kernel_cache_misses=self.calls,primitive_uses=self.uses)


def independent_selection(C,t,refs):
    """Test oracle. Full known keys may be inspected here, never in production."""
    keys=tuple(0 if x is None else C.key(*x) for x in refs)
    active=list(range(len(refs)));colors=list(range(C.colors));k=0;count=0
    while active:
        count+=len(active)
        halves=[[c for c in colors if (C.key(t,c)>>k)&1==b] for b in (0,1)]
        groups=[[i for i in active if (keys[i]>>k)&1==b] for b in (0,1)]
        eligible=[b for b in (0,1) if len(groups[b])<len(halves[b])]
        b=min(eligible,key=lambda b:(len(groups[b]),b))
        active=groups[b];colors=halves[b];k+=1
    return min(colors),count


def expected(C,table,cache,op):
    if op[0]!='reserve':
        after,answer=base.expected(C,table,op)
        newcache=prior.prior.expected_cache(C,table,cache,op,after,answer)
        return after,answer,newcache
    t=op[1];cur,refs=table
    can=not any(cur[s] is not None for s in C.conflicts[t])
    if not can:return table,False,tuple(cache)
    c,_=independent_selection(C,t,refs)
    ck(all(x!=(t,c) for x in refs),'selected color not referenced, including stale references')
    cur=list(cur);cur[t]=c;cache=list(cache);cache[t]=C.key(t,c)
    return (tuple(cur),refs),True,tuple(cache)


def audit(slots=1,start=0,stop=None,all_ops=False):
    C=Compiler(slots=slots);dom=base.domain(C);stop=len(dom) if stop is None else min(stop,len(dom))
    nops=0;mass=ZERO;maxreads=0;birthchecks=0
    for n in range(start,stop):
        table=dom[n];cache=list(C.initial_cache(table))
        for t,c in enumerate(table[0]):
            if c is None:cache[t]=(7*n+5*t+3)%(1<<C.bits)
        J=C.encode(table,(None,0,1)[n%3],cache)
        ops=base.Compiler.alphabet(C) if all_ops else tuple(('reserve',t) for t in range(C.d))
        for op in ops:
            want,ans,wc=expected(C,table,cache,op)
            if op[0]=='reserve':
                K,wm,dat=C.allocate(J,op[1]);maxreads=max(maxreads,dat['read_bits'])
                ck(dat['read_bits']<=2*slots-slots.bit_count(),'linear bit-read upper bound')
                if ans:
                    _,oracle_reads=independent_selection(C,op[1],table[1])
                    ck(dat['read_bits']==oracle_reads,'independent selection read count')
                    cost=3*len(C.conflicts[op[1]])+9+8*dat['read_bits']+C.bits+2+dat['key'].bit_count()+4*(1-dat['last'])
                else:cost=3*len(C.conflicts[op[1]])+9
                ck(dat['commands']==cost,'exact realized command formula')
            else:K,wm,_=C.run(J,op)
            ck(K==C.encode(want,ans,wc),'entire matching, source, references, caches, answer, clean workspace')
            ck(C.decode(K)==(want,ans),'abstract endpoint')
            oldwant,oldans=base.expected(C,table,op)
            ck(base.canon(C,want)==base.canon(C,oldwant) and ans==oldans,
               'same source and alias partition as parent, up to finite-color renaming')
            nops+=1;mass=r.merge(mass,wm)
    ck(mass.count==nops,'positive CWM retains every audited input-operation path')
    return dict(mode='audit',domain=len(dom),slice=[start,stop],all_ops=all_ops,
                operations=nops,max_bit_reads=maxreads,CWM=e.cw(mass),**C.metrics())


def costs(slots=6,d=3):
    H=base.H_DEFAULT if d==3 else tuple((3*i+1,3*i+2,3*i+3) for i in range(d))
    C=Compiler(H=H,slots=slots);old=prior.Compiler(H=H,slots=slots)
    rows=[]
    for t in range(C.d):
        scenarios=[('empty',(None,)*slots),('saturated',tuple((t,c) for c in range(slots)))]
        scenarios += [('missing_'+str(c),tuple((t,j) for j in range(C.colors) if j!=c))
                      for c in range(C.colors)]
        vals=[]
        for name,refs in scenarios:
            table=((None,)*C.d,refs);cache=tuple((1<<C.bits)-1 for _ in range(C.d))
            J=C.encode(table,False,cache);O=old.encode(table,False,cache)
            K,_,dat=C.allocate(J,t,True);n0=old.uses;L,_,_=old.run(O,('reserve',t));cost0=old.uses-n0
            after,answer,wc=expected(C,table,cache,('reserve',t))
            ck(K==C.encode(after,answer,wc),'cost complete matching')
            ck(base.canon(C,C.decode(K)[0])==base.canon(old,old.decode(L)[0]),'cost semantic classes')
            # No initial source relation is removed by allocation.
            state=base.ref.old.seed(J)
            for item in dat['trace']:
                state,_,_=base.ref.old.raw_step(state,item['command'],C.H)
            ck(state.matching==K,'annotation uses same physical kernel')
            vals.append(dict(scenario=name,selected_color=dat['color'],key=dat['key'],
                             bit_reads=dat['read_bits'],commands=dat['commands'],parent_commands=cost0,
                             levels=dat['levels']))
        rows.append(dict(target=t,paths=vals,max_bit_reads=max(x['bit_reads'] for x in vals),
                         new_min=min(x['commands'] for x in vals),new_max=max(x['commands'] for x in vals),
                         parent=cost0))
    return dict(mode='costs',rows=rows,**C.metrics())


def theory(max_r=6,max_d=3):
    """Finite exhaustive controller evidence; model-state execution is in audit/costs."""
    cases=0;maxima=[]
    for slots in range(1,max_r+1):
        M=slots+1;b=slots.bit_length();B=1<<b
        # All ordered low-bit lists; targets differ only through interval offset mod B.
        for offset in range(B):
            best=0
            # Histograms are sufficient for the count/branch planner and cover all ordered lists.
            def histograms(n,k):
                if k==1:yield (n,);return
                for a in range(n+1):
                    for rest in histograms(n-a,k-1):yield (a,)+rest
            for hist in histograms(slots,B):
                candidates=tuple(range(offset,offset+M));hs=list(hist);n=slots;k=reads=0
                while n:
                    caps=tuple(sum(((x>>k)&1)==v for x in candidates) for v in (0,1))
                    cnt=tuple(sum(hs[x] for x in range(B) if (x>>k)&1==v) for v in (0,1))
                    ck(abs(caps[0]-caps[1])<=1,'prefix capacities balanced for a consecutive interval')
                    eligible=[v for v in (0,1) if cnt[v]<caps[v]]
                    ck(bool(eligible),'pigeonhole deficiency persists')
                    chosen=min(eligible,key=lambda v:(cnt[v],v));reads+=n
                    ck(cnt[chosen]<=n//2,'retained potential blockers at least halve')
                    n=cnt[chosen];candidates=tuple(x for x in candidates if (x>>k)&1==chosen)
                    hs=[a if ((x>>k)&1)==chosen else 0 for x,a in enumerate(hs)];k+=1
                answer=min(candidates)%B
                ck(hist[answer]==0,'selected residue absent from all sampled keys')
                ck(reads<=2*slots-slots.bit_count(),'sum-of-floors bound')
                best=max(best,reads);cases+=1
            ck(best==2*slots-slots.bit_count(),'worst count attained in full histogram domain')
            maxima.append(dict(slots=slots,offset=offset,maximum=best))
    return dict(mode='theory',histogram_cases=cases,max_slots=max_r,maxima=maxima,assertions=CHECKS)


def lifecycle(rounds=30):
    C=Compiler(slots=6);old=prior.Compiler(slots=6)
    tab=((None,)*3,(None,)*6);otab=tab;cache=C.initial_cache(tab)
    J=C.encode(tab);O=old.encode(tab);state=base.ref.old.seed(J);protect=None
    acts=newcost=oldcost=0;records=[]
    def call(op):
        nonlocal J,O,tab,otab,cache,state,protect,acts,newcost,oldcost
        n=C.uses;K,_,trace=C.run(J,op,True);newcost+=C.uses-n
        n=old.uses;L,_,_=old.run(O,op);oldcost+=old.uses-n
        after,answer,wc=expected(C,tab,cache,op);oldafter,oldanswer=base.expected(old,otab,op)
        ck(K==C.encode(after,answer,wc),'lifecycle exact new endpoint')
        ck(base.canon(C,after)==base.canon(old,oldafter) and answer==oldanswer,'lifecycle future-relevant equivalence')
        for line in trace:
            state,_,_=base.ref.old.raw_step(state,line['command'],C.H)
            if protect is not None:ck(state.names().get(C.targets[2])==protect,'C creation unchanged at every primitive')
        ck(state.matching==K,'birth-annotated execution equals production')
        if op==('reserve',2) and protect is None:protect=state.names()[C.targets[2]]
        if len(records)<45:records.append(dict(op=op,answer=answer,physical_current=after[0],parent_current=oldafter[0],commands=len(trace)))
        J,O,tab,otab,cache=K,L,after,oldafter,wc;acts+=1
    call(('reserve',2))
    for j in range(rounds):
        i=j%6;v=(i+1)%6;w=(i+2)%6
        for op in (('reserve',0),('bind',i,0),('copy',v,i),('same',i,v),('valid',i),
                   ('release',1),('valid',i),('bind',w,0),('reserve',0),('bind',w,0),
                   ('execute',i),('execute',w),('copy',i,v),('drop',v),('copy',i,i),('valid',5)):
            call(op)
    return dict(mode='lifecycle',rounds=rounds,api_calls=acts,commands=newcost,parent_commands=oldcost,
                trace=records,**C.metrics())


def failures():
    C=Compiler(slots=6);out={}
    # Omit a registered stale reference from the candidate exclusion scan.
    for t in range(3):
        for missing in range(C.colors):
            refs=tuple((t,c) for c in range(C.colors) if c!=missing)
            tab=((None,)*3,refs);J=C.encode(tab)
            for drop in range(6):
                K,_,bad=C.allocate(J,t,slot_subset=[i for i in range(6) if i!=drop])
                if (t,bad['color']) in refs:
                    V,_,_=C.run(K,('valid',refs.index((t,bad['color']))))
                    ck(C.observe_result(V),'omitted stale reference spuriously revived')
                    good,_,gd=C.allocate(J,t)
                    ck((t,gd['color']) not in refs,'all registered references avoid resurrection')
                    out['skipped_stale_reference']=dict(target=t,refs=refs,omitted_slot=drop,
                        wrong_color=bad['color'],safe_color=gd['color'],bad_valid=True)
                    break
            if out:break
        if out:break
    ck(bool(out),'explicit stale-reference witness found')
    # No free color is lost, even though foreign keys and empty slots can over-exclude.
    tab=((None,)*3,((1,0),None,None,None,None,None))
    J=C.encode(tab);K,_,good=C.allocate(J,0)
    ck((0,good['color']) not in tab[1],'cross-target conservative blocking remains safe')
    out['conservative_foreign']=dict(refs=tab[1],selected=good['color'],read_bits=good['read_bits'])
    # A source-index update in between bit sampling and final creation may invalidate the proof.
    J=C.encode(((None,)*3,(None,)*6));_,_,plan=C.allocate(J,0,True)
    suffix=C.create_words[0,plan['color'],plan['last']]
    prefix=plan['word'][:-len(suffix)]
    mid,_,_=C.runword(J,prefix)
    # Cooperative snapshot condition deliberately broken: create, bind, retire the chosen identity.
    c=plan['color'];tab=((c,None,None),(None,)*6)
    # Establish a real current instance without external test-value filling in the trace.
    ww=C.clear_shared(0)+[p.add(C.current[0].cell(c)),p.add(C.targets[0])]
    ww += [p.add(C.shared[0][b]) for b in range(C.bits) if C.key(0,c)>>b&1]
    mid,_,_=C.runword(mid,ww)
    mid,_,_=C.run(mid,('bind',0,0));mid,_,_=C.run(mid,('release',1))
    # Restore last observed result only: allocation controller is still using its old decision.
    mid,_,_=C.runword(mid,C.clearout()+[p.add(h) for h in p.reg(C.out,plan['last'])])
    K,_,_=C.runword(mid,suffix);V,_,_=C.run(K,('valid',0))
    ck(C.observe_result(V),'snapshot break revives an intervening retired request')
    out['unprotected_race']=dict(selected_color=c,intervening_actions=['create chosen identity','bind reference0','retire target'],
                                  late_commit='creates same color from stale exclusion evidence',old_reference_now_valid=True)
    return dict(mode='failures',witnesses=out,**C.metrics())


if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('mode',choices=['audit','costs','theory','lifecycle','failures'])
    ap.add_argument('--slots',type=int,default=1);ap.add_argument('--d',type=int,default=3)
    ap.add_argument('--start',type=int,default=0);ap.add_argument('--stop',type=int)
    ap.add_argument('--all-ops',action='store_true');ap.add_argument('--max-r',type=int,default=6)
    ap.add_argument('--rounds',type=int,default=30);ap.add_argument('--out')
    x=ap.parse_args()
    if x.mode=='audit':ans=audit(x.slots,x.start,x.stop,x.all_ops)
    elif x.mode=='costs':ans=costs(x.slots,x.d)
    elif x.mode=='theory':ans=theory(x.max_r)
    elif x.mode=='lifecycle':ans=lifecycle(x.rounds)
    else:ans=failures()
    text=json.dumps(ans,ensure_ascii=False,indent=2)+'\n'
    if x.out:Path(x.out).write_text(text)
    else:print(text)
