"""Test every small exchange that could remove one label from the 56-label four-service table."""
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from itertools import combinations,product
from pathlib import Path
from tempfile import TemporaryDirectory
import argparse,json,subprocess
HERE=Path(__file__).resolve().parent

def verify(previous,jobs):
    second=previous/'previous/previous/previous/previous'
    data=json.loads((second/'four/certificate.json').read_text())
    points=list(product(range(5),repeat=4))
    def shift(i,t):
        return sum(((a+t)%5)*5**(3-j)for j,a in enumerate(points[i]))
    rows=[[shift(i,t)for i in row]for row in data['templates']for t in range(5)]
    left=set(range(625)).difference(*rows);assert len(left)==5
    rows.append(sorted(left))
    assert len(rows)==56 and sorted(sum(rows,[]))==list(range(625))
    def act(j,t):return 5*(j//5)+(j+t)%5 if j<55 else 55
    def inspect(k,work):
        # The cyclic group of order five generated by diagonal translation permutes whole labels.
        active=[];raw=0
        sizes=list(map(len,rows))
        for pick in combinations(range(56),k):
            size=sum(sizes[j]for j in pick)
            if size>12*(k-1):continue
            raw+=1
            if any(tuple(sorted(act(j,t)for j in pick))<pick for t in range(1,5)):continue
            union=sorted(x for j in pick for x in rows[j])
            active.append(union)
        def shard(i):
            text=''.join(' '.join(map(str,[j,k-1,len(q),*q]))+'\n'for j,q in enumerate(active)if j%8==i)
            raw=subprocess.check_output([work/'search'],input=text,text=True)
            return [tuple(map(int,line.split()))for line in raw.splitlines()]
        with ThreadPoolExecutor(jobs)as ex:
            result=sorted(r for group in ex.map(shard,range(8))for r in group)
        assert [r[0]for r in result]==list(range(len(active)))
        assert all(len(r)==4 and r[3]==0 for r in result)
        return dict(capacity_feasible_subsets=raw,orbits=len(active),candidate_rows=sum(r[1]for r in result),cover_nodes=sum(r[2]for r in result))
    with TemporaryDirectory()as tmp:
        w=Path(tmp)
        subprocess.run(['c++','-O3','-std=c++20','-mpopcnt',HERE/'search.cpp','-o',w/'search'],check=True)
        return {str(k):inspect(k,w)for k in range(2,6)}
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--previous',type=Path,required=True);p.add_argument('--jobs',default=3,type=int)
    args=p.parse_args();print(json.dumps(verify(args.previous.resolve(),args.jobs),indent=2,sort_keys=True))
