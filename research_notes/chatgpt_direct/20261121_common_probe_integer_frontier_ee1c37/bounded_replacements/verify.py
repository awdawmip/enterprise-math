"""Portable exact verification of the bounded replacements and fixed-core dual.

The input bank and full census seeds are regenerated by ../lower/replay.py.
The native menus below independently rebuild the observation and triple file.
"""
from collections import Counter
from hashlib import sha256
from itertools import combinations, product
from pathlib import Path
import argparse
import importlib.util
import json
import struct
import subprocess

HERE = Path(__file__).resolve().parent
POINTS = list(product(range(5), repeat=3))
MENUS = []
for d, start in product((1, 3), POINTS):
    menu = []
    for point in POINTS:
        active = sum(1 << j for j in range(3) if (point[j]-start[j]) % 5 in (0, d))
        target = tuple(point[j] for j in range(3) if active >> j & 1)
        menu.append((active, target))
    MENUS.append(menu)


def evaluate(ids):
    cost = 0
    for menu in MENUS:
        fibers = {}
        for p in ids:
            active, target = menu[p]
            counts = fibers.setdefault(active, Counter())
            counts[target] += 1
        assert all(len(counts) <= 2 for counts in fibers.values())
        cost += sum(sum(counts.values()) for counts in fibers.values() if len(counts) == 2)
    return cost


def observations(path):
    pair = [[0]*125 for _ in range(125)]
    triples = set()
    for t, menu in enumerate(MENUS):
        fibers = {}
        for p, (active, target) in enumerate(menu):
            fibers.setdefault(active, {}).setdefault(target, []).append(p)
        for groups in fibers.values():
            values = list(groups.values())
            for a, b in combinations(values, 2):
                for x, y in product(a, b):
                    pair[x][y] |= 1 << t
                    pair[y][x] |= 1 << t
            for a, b, c in combinations(values, 3):
                for x, y, z in product(a, b, c):
                    triples.add(tuple(sorted((x, y, z))))
    assert len(triples) == 47000
    with path.open('wb') as out:
        for row in pair:
            for value in row:
                out.write(value.to_bytes(32, 'little'))
        for triple in sorted(triples):
            out.write(bytes(triple))
    return {'menus': 250, 'forbidden_triples': len(triples),
            'sha256': sha256(path.read_bytes()).hexdigest()}


def initial():
    rows, costs = [], []
    for line in (HERE/'initial.txt').read_text().splitlines():
        n, c, *ids = map(int, line.split())
        assert len(ids) == n and len(set(ids)) == n
        assert evaluate(ids) == c
        rows.append(ids); costs.append(c)
    assert len(rows) == 12 and sorted(sum(rows, [])) == list(range(125))
    assert sum(costs) == 9996 and [len(r) for r in rows] == [13, 13, 9]+[10]*9
    return rows, costs


def check_dual(previous, bank_path, seeds_path, rows, costs):
    dual = json.loads((HERE/'point_dual.json').read_text())
    weights = {int(p): v for p, v in dual['point_weights'].items()}
    b = dual['class_weight']
    free = set(range(125))-set(rows[0])-set(rows[1])
    assert set(weights) == free and len(free) == 99
    assert b == -1180 and min(weights.values()) == 187 and max(weights.values()) == 196
    caps = {n: n*max(weights.values())+b for n in (9, 10)}
    assert caps == {9: 584, 10: 780}
    raw_seeds = seeds_path.read_bytes()
    assert sha256(raw_seeds).hexdigest() == dual['source_seeds_sha256']
    needed = set()
    seed_rows = 0
    for line in raw_seeds.splitlines():
        n, c = map(int, line.split(None, 2)[:2])
        seed_rows += 1
        if n in caps and c <= caps[n]: needed.add((n, c))
    assert seed_rows == 1495322
    assert sorted(needed) == [(9, 557), (9, 564), (9, 569), (9, 576),
                             (10, 744), (10, 747), (10, 752), (10, 768),
                             (10, 772), (10, 777), (10, 780)]
    raw_bank = bank_path.read_bytes()
    assert sha256(raw_bank).hexdigest() == dual['source_bank_sha256']
    assert len(raw_bank) == 426500*24
    spec = importlib.util.spec_from_file_location('replacement_native',
                                                previous/'fractional/proof/verify.py')
    native = importlib.util.module_from_spec(spec); spec.loader.exec_module(native)
    bad, pair = native.observation_tables()
    fixed_mask = sum(1 << p for p in set(rows[0]) | set(rows[1]))
    counts, minimum = Counter(), {}
    all_types = set()
    for lo, hi, c, tag in struct.iter_unpack('<QQII', raw_bank):
        kind = tag % 256, c
        all_types.add(kind)
        mask = lo | (hi << 64)
        if kind not in needed or mask & fixed_mask: continue
        assert native.native_class(mask, bad, pair) == kind
        ids = [p for p in free if mask >> p & 1]
        slack = c-sum(weights[p] for p in ids)-b
        assert slack >= 0
        counts[kind] += 1
        minimum[kind] = min(minimum.get(kind, slack), slack)
    assert needed <= all_types
    shift = costs[0]+costs[1]+sum(weights.values())+10*b
    assert shift == 9872
    # Costs above caps automatically satisfy c >= sum(weights)+b.
    return {'scope': 'The two specified 13-point classes fixed, one 9-point and nine 10-point classes',
            'full_seed_rows': seed_rows, 'full_bank_rows': 426500,
            'automatic_thresholds': caps, 'checked_native_classes': sum(counts.values()),
            'types': [dict(size=n, cost=c, checked=counts[n, c], minimum_slack=minimum[n, c])
                      for n, c in sorted(counts)], 'fixed_core_cost': sum(costs[:2]),
            'free_cover_dual': shift-sum(costs[:2]), 'total_lower_bound': shift,
            'all_above_threshold_classes_covered_by_max_weight_bound': True}


def check_positive(result, rows):
    assert result['complete'] and result['found'] and len(result['groups']) == 12
    assert sorted(g['old_label'] for g in result['groups']) == list(range(12))
    assert sorted(sum((g['points'] for g in result['groups']), [])) == list(range(125))
    total = 0
    for group in result['groups']:
        old = set(rows[group['old_label']]); new = set(group['points'])
        assert len(old) == len(new) and len(old-new) <= result['radius']
        assert evaluate(group['points']) == group['cost']
        total += group['cost']
    assert total == 9996 and total <= result['budget']
    return {'direct_menu_count': 250, 'classes': 12, 'cost': total,
            'same_original_partition': all(set(g['points']) == set(rows[g['old_label']])
                                           for g in result['groups'])}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--previous', type=Path, required=True)
    p.add_argument('--bank', type=Path, required=True)
    p.add_argument('--seeds', type=Path, required=True)
    p.add_argument('--work', type=Path, required=True)
    p.add_argument('--radius', type=int, choices=[2, 3, 4, 5], default=4)
    p.add_argument('--dual-only', action='store_true')
    a = p.parse_args(); a.work.mkdir(parents=True, exist_ok=True)
    rows, costs = initial()
    result = {'initial_cost': sum(costs), 'dual': check_dual(a.previous.resolve(),
                                          a.bank, a.seeds, rows, costs)}
    if not a.dual_only:
        result['observations'] = observations(a.work/'obs')
        runs = []
        for variant in ('pool', 'dual'):
            executable = a.work/variant
            subprocess.run(['c++', '-std=c++20', '-O3', '-mpopcnt',
                            HERE/f'bounded_replacements_{variant}.cpp', '-o', executable], check=True)
            args = [str(executable), str(a.work/'obs'), str(HERE/'initial.txt'), str(a.radius), '9995']
            if variant == 'dual': args.append(str(HERE/'point_dual.txt'))
            run = json.loads(subprocess.check_output(args, text=True))
            assert run['complete'] and not run['found']
            assert run['radius'] == a.radius and run['budget'] == 9995
            runs.append({'variant': variant, **run})
        assert runs[0]['legal_candidates_before_price_cap'] == runs[1]['legal_candidates_before_price_cap']
        result['bounded_replacements'] = runs
        args = [str(a.work/'dual'), str(a.work/'obs'), str(HERE/'initial.txt'), '2', '9996',
                str(HERE/'point_dual.txt')]
        positive = json.loads(subprocess.check_output(args, text=True))
        result['positive_control'] = check_positive(positive, rows)
    result['source_sha256'] = {f: sha256((HERE/f).read_bytes()).hexdigest()
                              for f in ('verify.py', 'bounded_replacements_pool.cpp',
                                        'bounded_replacements_dual.cpp', 'initial.txt',
                                        'point_dual.json', 'point_dual.txt')}
    (a.work/'result.json').write_text(json.dumps(result, indent=2)+'\n')
    print(json.dumps(result, indent=2), flush=True)


if __name__ == '__main__':
    main()
