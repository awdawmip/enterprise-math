#!/usr/bin/env python3
"""Exact F_2 exhaustive orbit check for pairs (X:k^2->k^m,Y:k^m->k^2).

This is an auxiliary finite-field model, not a native Enterprise Math H0/B0 run.
GL_m(F_2) x GL_2(F_2) is generated by the elementary transvections
E_{i,i+1}(1) and E_{i+1,i}(1), each self-inverse.
"""
import json
from collections import Counter


def xrank(x, m):
    rows = [(x >> (2 * i)) & 3 for i in range(m)]
    if not any(rows):
        return 0
    # F_2^2: exactly two distinct nonzero row vectors => rank 2.
    return 2 if len({v for v in rows if v}) >= 2 else 1


def apply_t(state, m, side, i, j):
    # Apply (I+E_ij) on V=k^m or W=k^2, respecting X'=gV X gW^-1,
    # Y'=gW Y gV^-1. In characteristic 2 transvections are self-inverse.
    size_x = 2 * m
    mask = (1 << size_x) - 1
    x = state & mask
    y0 = (state >> size_x) & ((1 << m) - 1)
    y1 = (state >> (size_x + m)) & ((1 << m) - 1)
    if side == 'V':
        source_row = (x >> (2*j)) & 3
        x ^= source_row << (2*i)  # row_i(X) <- row_i(X)+row_j(X)
        if (y0 >> i) & 1:
            y0 ^= 1 << j  # col_j(Y) <- col_j(Y)+col_i(Y)
        if (y1 >> i) & 1:
            y1 ^= 1 << j
    else:
        # W side: col_j(X) <- col_j(X)+col_i(X)
        for k in range(m):
            if (x >> (2*k+i)) & 1:
                x ^= 1 << (2*k+j)
        if i == 0:
            y0 ^= y1
        else:
            y1 ^= y0
    return x | (y0 << size_x) | (y1 << (size_x+m))


def orbit_census(m):
    n_states = 1 << (4 * m)
    seen = bytearray(n_states)
    gens = [('V', i, i+1) for i in range(m-1)] + \
           [('V', i+1, i) for i in range(m-1)] + \
           [('W', 0, 1), ('W', 1, 0)]
    by_rank = Counter()
    orbit_sizes_by_rank = {0: Counter(), 1: Counter(), 2: Counter()}
    num = 0
    directed_checks = 0
    for s in range(n_states):
        if seen[s]:
            continue
        r = xrank(s & ((1 << (2*m))-1), m)
        num += 1
        by_rank[r] += 1
        seen[s] = 1
        todo = [s]
        head = 0
        while head < len(todo):
            a = todo[head]
            head += 1
            # RankX invariant under group action.
            for side,i,j in gens:
                b = apply_t(a, m, side, i, j)
                directed_checks += 1
                if not seen[b]:
                    assert xrank(b & ((1 << (2*m))-1), m) == r
                    seen[b] = 1
                    todo.append(b)
        orbit_sizes_by_rank[r][len(todo)] += 1
    assert all(seen)
    expected = (3, 2*2+3 if m==2 else 2*2+4,
                2**2+2 if m==2 else (2**2+2*2+1 if m==3 else 2**2+2*2+2))
    assert tuple(by_rank[i] for i in range(3)) == expected, (m, by_rank, expected)
    assert num == (2**2+3*2+6 if m==2 else 2**2+4*2+(8 if m==3 else 9))
    return {
        'm':m,'q':2,'n_states':n_states,'orbit_count':num,
        'orbits_by_rank_X':{str(i):by_rank[i] for i in range(3)},
        'orbit_size_histograms':{str(i):dict(sorted(orbit_sizes_by_rank[i].items())) for i in range(3)},
        'directed_generator_actions':directed_checks,
        'group_generators':['adjacent V transvections both orientations', 'two W transvections'],
        'status':'PASS_EXHAUSTIVE'
    }


def main():
    cases = [orbit_census(m) for m in (2,3,4)]
    print(json.dumps({
        'model':'A=diag(a*I_m,b*I_2), a!=b, K=[B,A] with two off-diagonal maps',
        'scope':'finite field F_2 for complete orbit enumeration; general q theorem proved algebraically',
        'cases':cases,
        'all_pass':True,
        'native_h0_b0_experiment':False,
        'independent_review':False,
        'source_checkpoint':False
    },indent=2,sort_keys=True))


# An independent odd-characteristic route, intentionally separate from the binary
# bitwise implementation above. It includes determinant-changing diagonal scalings.
def orbit_census_odd(q, m):
    assert q == 3 and m in (2,3)
    total = q ** (4*m)
    powers = [q**i for i in range(4*m)]
    gen = [('V', i, i+1) for i in range(m-1)] + \
          [('V', i+1, i) for i in range(m-1)] + \
          [('W', 0, 1), ('W', 1, 0), ('VS',0,0), ('WS',0,0)]
    cache=[]
    for side,i,j in gen:
        changes=[]
        if side == 'V':
            for c in range(2): changes.append((2*i+c,2*j+c,1))
            for r in range(2): changes.append((2*m+r*m+j,2*m+r*m+i,-1))
        elif side == 'W':
            for r in range(m): changes.append((2*r+j,2*r+i,-1))
            for c in range(m): changes.append((2*m+i*m+c,2*m+j*m+c,1))
        elif side == 'VS':
            for c in range(2): changes.append((c,c,-2))
            for r in range(2): changes.append((2*m+r*m,2*m+r*m,-2))
        else:
            for r in range(m): changes.append((2*r,2*r,-2))
            for c in range(m): changes.append((2*m+c,2*m+c,-2))
        cache.append(changes)
    def act(state, changes):
        out=state
        for dst,src,coeff in changes:
            old=(state//powers[dst])%3
            new=(old+coeff*((state//powers[src])%3))%3
            out+=(new-old)*powers[dst]
        return out
    def rankx(s):
        v=[((s//powers[2*r])%3,(s//powers[2*r+1])%3) for r in range(m)]
        if not any(a or b for a,b in v): return 0
        for a,b in v:
            for c,d in v:
                if (a*d-b*c)%3: return 2
        return 1
    seen=bytearray(total)
    counts=Counter()
    orbit_count=0
    actions=0
    for s in range(total):
        if seen[s]:continue
        r=rankx(s)
        orbit_count+=1
        counts[r]+=1
        pending=[s];seen[s]=1
        at=0
        while at<len(pending):
            item=pending[at];at+=1
            for changes in cache:
                t=act(item,changes)
                actions+=1
                if not seen[t]:
                    seen[t]=1
                    pending.append(t)
        assert sum(counts.values())==orbit_count
    expected=(3,2*q+(3 if m==2 else 4),
              (q*q+q if m==2 else q*q+2*q+1))
    assert tuple(counts[i] for i in range(3)) == expected,(m,counts,expected)
    return {'m':m,'q':q,'n_states':total,'orbits_by_rank_X':{str(i):counts[i] for i in range(3)},'orbit_count':orbit_count,'directed_generator_actions':actions,'status':'PASS_EXHAUSTIVE'}

