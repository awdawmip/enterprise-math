def prime_trial(q):
    if q < 2 or q % 2 == 0:
        return q == 2
    return all(q % d for d in range(3,isqrt(q)+1,2))


def order_two(q):
    value = 1
    for d in range(1,433):
        value = 2*value % q
        if value == 1:
            return d
    raise AssertionError(('order outside declared exact search range',q))


def native_setup(source_dir):
    checks = {}
    for filename, expected in NATIVE_BLOBS.items():
        data = (source_dir/'enterprise_math'/filename).read_bytes()
        actual = sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest()
        assert actual == expected
        checks[filename] = actual
    sys.path.insert(0,str(source_dir))
    from enterprise_math.brc_transport import Affine, EffectHistogram, euclidean_digits, recompose
    step = EffectHistogram.from_terms(1,[(1,Affine(((2,),),(1,)),1)])
    twice = step.then(step)
    assert twice.entries == ((Fraction(1),Affine(((4,),),(3,)),1),)

    def evaluate(effect,x):
        (point,weight), = effect.evaluate((x,)).items()
        assert weight.entries == ((Fraction(1),1),)
        assert point[0].denominator == 1
        return int(point[0])

    return checks,step,twice,evaluate,euclidean_digits,recompose


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir',type=Path)
    parser.add_argument('--output',type=Path,default=HERE/'exact_total_certificate.json')
    args = parser.parse_args()
    native = native_setup(args.source_dir) if args.source_dir else None
    primes = sorted(set(P).union(*(set(case['supplement']) for case in CASES)))
    assert all(prime_trial(q) for q in primes)
    orders = {q:order_two(q) for q in primes}
    result = {
        'schema':'RIESEL_COMPACT_EXACT_TOTAL_V14', 'status':'PASS',
        'date':'2026-11-24', 'old_dictionary':P,
        'prime_verification':'Deterministic trial division through floor(sqrt(q)), with every odd trial divisor.',
        'exact_orders':orders, 'cases':[],
        'classification_dependency':'Only the stated global-minimum scopes use previous classification theorems; each displayed delta and tau equality is proved by this certificate.',
        'native_execution':bool(native),
    }
    started = time.monotonic()
    counts = dict(one_step_updates=0,two_step_evaluations=0,prime_readouts=0,
                  joint_readouts=0,joint_recompositions=0,retained_witnesses=0,gcd_one_pairs=0)
    for case in CASES:
        a = case['root']
        dictionary = sorted(set(P)|set(case['supplement']))
        m = 20+case['supplementary_cost']
        assert len(dictionary) == len(case['witnesses']) == m
        assert set(q for q,n in case['witnesses']) == set(dictionary)
        assert len(set(n for q,n in case['witnesses'])) == m
        assert a*a-1 > max(dictionary)
        phase = {}
        for q in dictionary:
            hits = [n for n in range(orders[q]) if a*a*pow(2,n,q)%q == 1]
            assert len(hits) == 1
            phase[q] = hits[0]
        period = lcm(*(orders[q] for q in dictionary))
        assert period == (60480 if case['supplementary_cost'] == 9 else 20160)
        masks = [0]*period
        for bit,q in enumerate(dictionary):
            for n in range(phase[q],period,orders[q]):
                masks[n] |= 1<<bit
        assert all(masks)
        terms = {n:(a*a<<n)-1 for q,n in case['witnesses']}
        witnesses = []
        for q,n in case['witnesses']:
            value = terms[n]
            assert value > q > 1 and value % q == 0
            assert [r for r in dictionary if value % r == 0] == [q]
            witnesses.append(dict(prime=q,n=n,state_hex=hex(value),cofactor_hex=hex(value//q)))
        gcds = [gcd(terms[n],terms[k]) for (_,n),(_,k) in combinations(case['witnesses'],2)]
        assert len(gcds) == m*(m-1)//2 and set(gcds) == {1}
        counts['retained_witnesses'] += m
        counts['gcd_one_pairs'] += len(gcds)
        record = {
            'name':case['name'], 'root':str(a), 'root_digits':len(str(a)),
            'family':case['family'], 'minimum_provenance':case['minimum_provenance'],
            'supplement':case['supplement'], 'dictionary':dictionary,
            'cover_period':period, 'uncovered':0, 'zero_phases':phase,
            'delta_exact':case['supplementary_cost'], 'tau_exact':m,
            'witness_count':m, 'max_witness_index':max(terms),
            'pairwise_gcd_one_count':len(gcds), 'witnesses':witnesses,
        }
        if native:
            checks,step,twice,evaluate,euclidean_digits,recompose = native
            x = previous_even = a*a-1
            digest = sha256()
            actual_terms = {}
            for n in range(1,max(terms)+1):
                x = evaluate(step,x)
                assert x == (a*a<<n)-1
                counts['one_step_updates'] += 1
                if n % 2 == 0:
                    assert evaluate(twice,previous_even) == x
                    previous_even = x
                    counts['two_step_evaluations'] += 1
                for q in dictionary:
                    quotient,(residue,) = euclidean_digits(x,(q,))
                    assert (quotient,residue) == divmod(x,q)
                    counts['prime_readouts'] += 1
                quotient,digits = euclidean_digits(x,dictionary)
                assert recompose(quotient,digits,dictionary) == x
                counts['joint_readouts'] += 1
                counts['joint_recompositions'] += 1
                data = x.to_bytes((x.bit_length()+7)//8,'big')
                digest.update(len(data).to_bytes(8,'big'))
                digest.update(data)
                if n in terms:
                    actual_terms[n] = x
            assert actual_terms == terms
            assert all(gcd(actual_terms[n],actual_terms[k]) == 1
                       for n,k in combinations(actual_terms,2))
            record['native'] = dict(updates=max(terms),full_witnesses_retained=len(actual_terms),
                last_state_hex=hex(x),last_state_bits=x.bit_length(),
                integer_stream_sha256=digest.hexdigest(),
                executed_interval_scope='Witness production through the last listed index; complete-period upper coverage is checked separately above.')
        result['cases'].append(record)
    result['actual_counts'] = counts
    result['elapsed_seconds'] = time.monotonic()-started
    if native:
        result['native_source_commit'] = NATIVE_COMMIT
        result['native_source_blobs'] = native[0]
        result['native_semantics'] = 'Fixed X6 anchor, full typed integer register, positive singleton BRC weight and multiplicity one; x -> 2x+1, with joint quotient-chain reconstruction.'
