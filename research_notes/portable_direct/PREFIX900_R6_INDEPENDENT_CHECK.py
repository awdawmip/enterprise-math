#!/usr/bin/env python3
"""Independent direct enumeration checks for PREFIX-900 periodic two-bit counting.

Uses a separate Python implementation from the C++ finite-census code.
Run: python3 PREFIX900_R6_INDEPENDENT_CHECK.py [expanded_panel_json]
Expanded JSON is generated by PREFIX900_R6_PANEL_REPRODUCE.py.
"""
import random, json, sys
random.seed(900)

def bitones(t,bit):
    h=1<<bit; p=2*h
    return t//p*h+max(0,t%p-h)

def bitcount(l,r,bit,value,shift=0):
    if l>r:return 0
    h=1<<bit; shift%=2*h
    ones=bitones(r+shift+1,bit)-bitones(l+shift,bit)
    return ones if value else r-l+1-ones

def exact_intersection(l,r,i,bi,j,bj,d):
    h=max(i,j); half=1<<h; period=2*half
    def ring(start,length):
        s=start%period
        if s+length<=period:return [(s,s+length-1)]
        return [(s,period-1),(0,s+length-period-1)]
    high=ring(bi*half,half) if i>=j else ring(bj*half-d,half)
    if i==j:
        second=ring(bj*half-d,half)
        high=[(max(a,c),min(b,e)) for a,b in high for c,e in second
              if max(a,c)<=min(b,e)]
    low=min(i,j)
    def inside(t):
        if t<=0:return 0
        n=0
        for a,b in high:
            if a>=t:continue
            end=min(b,t-1)
            n+=(end-a+1) if i==j else bitcount(
                a,end,low,bi if i<j else bj,0 if i<j else d)
        return n
    full=inside(period)
    def prefix(t):return t//period*full+inside(t%period)
    return prefix(r+1)-prefix(l)

checks=0
for p in range(1,11):
    N=1<<p
    for _ in range(220):
        i=random.randrange(p);j=random.randrange(p)
        bi=random.randrange(2);bj=random.randrange(2)
        d=random.randrange(-N+1,N)
        l=max(0,-d);r=min(N-1,N-1-d)
        if l<=r:
            l=random.randrange(l,r+1)
            r=random.randrange(l,r+1)
        got=exact_intersection(l,r,i,bi,j,bj,d)
        want=sum(((x>>i)&1)==bi and (((x+d)>>j)&1)==bj
                 for x in range(l,r+1))
        assert got==want,(p,i,j,bi,bj,d,l,r,got,want)
        checks+=1

witness_count=None
if len(sys.argv)==2:
    panel=json.load(open(sys.argv[1],encoding="utf-8"))
    witnesses=[(row["q1"],w) for row in panel["rows"]
               for w in row["general_witnesses"]]
    for a,w in witnesses:
        b=w["q2"]; x=w["x"]; y=w["y"]; i=w["i"]; j=w["j"]
        assert 0<=x<(1<<32) and 0<=y<(1<<32)
        assert 0<=i<32 and 0<=j<32
        assert x!=y or i!=j
        assert x%a==y%a and (x^(1<<i))%b==(y^(1<<j))%b
    witness_count=len(witnesses)
    assert witness_count==449
print(json.dumps({"schema":"PREFIX900_R6_INDEPENDENT_CHECK_V1",
                  "seed":900,"small_bitcount_exhaustive_interval_checks":checks,
                  "general_witnesses_independently_verified":witness_count,
                  "status":"PASS"},indent=2))
