"""PREFIX-794: joint-path reconstruction and future-observer rank under localized toggles."""
from itertools import product
from fractions import Fraction
from pathlib import Path
import json


def cube_from_x(K,x):
    return {(a,i,j):(x[i][j] if a==0 else K[i][j]-x[i][j])
            for i in range(len(K)) for j in range(len(K[0])) for a in (0,1)}


def pairs(n,B,C):
    P={(a,i):sum(n[a,i,j] for j in range(C)) for a in (0,1) for i in range(B)}
    Q={(a,j):sum(n[a,i,j] for i in range(B)) for a in (0,1) for j in range(C)}
    R={(i,j):sum(n[a,i,j] for a in (0,1)) for i in range(B) for j in range(C)}
    return P,Q,R


def toggle(n,B,C,i,j):
    out=dict(n)
    out[0,i,j],out[1,i,j]=n[1,i,j],n[0,i,j]
    return out


def recover(K,r,s,observed):
    B,C=len(K),len(K[0])
    x=[[None]*C for _ in range(B)]
    for i in range(B-1):
        for j in range(C-1): x[i][j]=observed[i,j]
        x[i][C-1]=r[i]-sum(x[i][j] for j in range(C-1))
    for j in range(C-1): x[B-1][j]=s[j]-sum(x[i][j] for i in range(B-1))
    x[B-1][C-1]=r[B-1]-sum(x[B-1][j] for j in range(C-1))
    assert s[C-1]==sum(x[i][C-1] for i in range(B))
    assert all(0<=x[i][j]<=K[i][j] for i in range(B) for j in range(C))
    return tuple(tuple(z) for z in x)


def mat_rank(matrix):
    A=[[Fraction(x) for x in row] for row in matrix]
    if not A: return 0
    rows, cols=len(A),len(A[0])
    rank=0
    for c in range(cols):
        pivot=next((z for z in range(rank,rows) if A[z][c]),None)
        if pivot is None: continue
        A[rank],A[pivot]=A[pivot],A[rank]
        p=A[rank][c]
        A[rank]=[v/p for v in A[rank]]
        for k in range(rank+1,rows):
            if A[k][c]:
                q=A[k][c]
                A[k]=[v-q*w for v,w in zip(A[k],A[rank])]
        rank+=1
        if rank==rows: break
    return rank


def row_operator(B,C):
    states=list(product((0,1),range(B),range(C)))
    pairs=[lambda q,a=a,i=i:q[0]==a and q[1]==i for a in (0,1) for i in range(B)]
    pairs +=[lambda q,a=a,j=j:q[0]==a and q[2]==j for a in (0,1) for j in range(C)]
    pairs +=[lambda q,i=i,j=j:q[1]==i and q[2]==j for i in range(B) for j in range(C)]
    return states, pairs


def stacked_rank(B,C,toggles):
    states,fs=row_operator(B,C)
    out=[[int(f(q)) for q in states] for f in fs]
    for i,j in toggles:
        transformed=[((1-a if (u,v)==(i,j) else a),u,v) for a,u,v in states]
        out.extend([[int(f(q)) for q in transformed] for f in fs])
    return mat_rank(out)


def check(K,x):
    B,C=len(K),len(K[0]);n=cube_from_x(K,x)
    P,Q,R=pairs(n,B,C)
    observed={}
    checks=0
    for i in range(B-1):
        for j in range(C-1):
            nt=toggle(n,B,C,i,j)
            P2,Q2,R2=pairs(nt,B,C)
            delta=P2[0,i]-P[0,i]
            assert delta==Q2[0,j]-Q[0,j]==K[i][j]-2*x[i][j]
            assert R==R2
            assert toggle(nt,B,C,i,j)==n
            observed[i,j]=(K[i][j]-delta)//2
            assert 2*observed[i,j]==K[i][j]-delta
            checks+=4
    r=tuple(P[0,i] for i in range(B));s=tuple(Q[0,j] for j in range(C))
    assert recover(K,r,s,observed)==x
    return checks+1


def main():
    test=checks=0
    for B,C,levels in [(2,2,(0,1,2)),(2,3,(0,1))]:
        for flat in product(levels,repeat=B*C):
            K=tuple(tuple(flat[i*C+j] for j in range(C)) for i in range(B))
            for u in product(*(range(K[i][j]+1) for i in range(B) for j in range(C))):
                x=tuple(tuple(u[i*C+j] for j in range(C)) for i in range(B))
                checks+=check(K,x);test+=1
    # All 991 feasible x in the 2x3x5 symmetric example, generated by independent columns.
    cols=[q for q in product(range(3),repeat=3) if sum(q)==3]
    K=((2,)*5,)*3
    examples=0
    for vv in product(cols,repeat=5):
        x=tuple(tuple(vv[j][i] for j in range(5)) for i in range(3))
        if all(sum(row)==5 for row in x):
            checks+=check(K,x);examples+=1
    assert examples==991
    base=stacked_rank(3,5,[])
    after_one=stacked_rank(3,5,[(0,0)])
    after_eight=stacked_rank(3,5,list(product(range(2),range(4))))
    assert (base,after_one,after_eight)==(22,23,30)
    even={(a,b,c):int((a+b+c)%2==0) for a,b,c in product((0,1),repeat=3)}
    odd ={(a,b,c):int((a+b+c)%2==1) for a,b,c in product((0,1),repeat=3)}
    Pe,Qe,Re=pairs(even,2,2);Po,Qo,Ro=pairs(odd,2,2)
    assert (Pe,Qe,Re)==(Po,Qo,Ro)
    ee=pairs(toggle(even,2,2,0,0),2,2)[0][0,0]
    oo=pairs(toggle(odd,2,2,0,0),2,2)[0][0,0]
    assert (ee,oo)==(0,2)
    result={'status':'ALL_CHECKS_PASS PREFIX794 FUTURE_SAFE_TOGGLE_CRT',
            'complete_small_cubes':test,'integer_checks':checks,
            'two_by_three_by_five':{'tested_cubes':examples,'base_pairwise_rank':base,
                'rank_after_one_toggle':after_one,'rank_after_eight_toggles':after_eight,
                'full_histogram_rank':30},
            'even_odd_parity':{'initial_pairwise_equal':True,'after_flip_a00_target_ab00':[ee,oo]}}
    with Path(__file__).with_name('PREFIX794_R6_FUTURE_SAFE_CRT_TOGGLE_RESULTS.json').open('w') as f:
        json.dump(result,f,indent=2,sort_keys=True);f.write('\n')
    print(json.dumps(result,indent=2));print(result['status'])
