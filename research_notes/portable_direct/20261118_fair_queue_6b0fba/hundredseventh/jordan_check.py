"""Exact certificates for the primitive Jordan spectral Dirichlet transform.

Run with Python 3.8 or later. No dependencies, network, or zero tables required.
The published Turing count for the first zeta zero is a separate theorem input.
"""
import json
from fractions import Fraction as F
from math import comb, factorial, isqrt, prod


def beta_values(nmax):
    values = [F(0), F(1, 6)]
    for n in range(2, nmax + 1):
        values.append(F(2, 2*n+1) * sum(values[j]*values[n-j] for j in range(1, n)))
    return values


def elementary_squares(n):
    coefficients = [1]
    for j in range(1, n):
        coefficients.append(0)
        for k in range(j, 0, -1):
            coefficients[k] += j*j * coefficients[k-1]
    return coefficients


def jordan_row(n, beta):
    e = elementary_squares(n)
    return [F(n, r)*beta[r]*F(factorial(2*r)*e[n-r], factorial(2*n))
            for r in range(1, n+1)]


def bernoulli_values(last):
    values = [F(1)]
    for k in range(1, last + 1):
        values.append(-sum(comb(k+1,j)*values[j] for j in range(k))/(k+1))
    return values


def newton_from_matrix(size, nmax):
    # Coefficients of det(L_M - u I)/M, generated by the actual tridiagonal
    # continuant, independently of elementary squares and zeta values.
    previous, current = [1], [2,-1]
    for order in range(2, size + 1):
        next_row = [0]*(order+1)
        for j, c in enumerate(current):
            next_row[j] += 2*c
            next_row[j+1] -= c
        for j, c in enumerate(previous):
            next_row[j] -= c
        previous, current = current, next_row
    m = size + 1
    assert current[0] == m
    poly = [F(c,m) for c in current] + [F(0)]*nmax
    moments = [F(0)]
    for n in range(1, nmax + 1):
        moments.append(-n*poly[n]-sum(poly[j]*moments[n-j] for j in range(1,n)))
    return moments


def sum_enclosure(n, height, beta):
    # Direct nonadjacent expression. Each square root gets a rational enclosure.
    precision = 10**10
    elementary = elementary_squares(n)
    lower, upper = F(0), F(0)
    for r in range(1,n):
        numerator = (F(n,r)*4**(n-r)*F(factorial(2*r),factorial(2*n))
                     * (beta[r]/beta[n])**2 * elementary[n-r])
        lo_den, hi_den = F(1), F(1)
        for j in range(2*r,2*n):
            squared = (j*j + height*height)*precision**2
            root = isqrt(squared)
            lo_den *= F(root,precision)
            hi_den *= F(root + (root*root != squared),precision)
        lower += numerator/hi_den
        upper += numerator/lo_den
    return lower, upper


def scaled_enclosure(lo, hi):
    scale = 10**10
    return [lo.numerator*scale//lo.denominator, -((-hi.numerator*scale)//hi.denominator)]


def envelope_ratio(r):
    if r == 2:
        return F(25)
    return F(147*r,4*(2*r-2)*(2*r-1))


def inverse_half_power(m, twice_exponent):
    # Directed rounding for m**(-twice_exponent/2).
    scale = 10**22
    denominator = m**twice_exponent
    k = isqrt(scale**2//denominator)
    return F(k,scale), F(k+(k*k*denominator != scale**2),scale)


def real_zeta(twice_exponent):
    cutoff = 96
    pairs = [inverse_half_power(m,twice_exponent) for m in range(1,cutoff+1)]
    exponent_minus_one = F(twice_exponent-2,2)
    return (sum(a for a,b in pairs)
            + inverse_half_power(cutoff+1,twice_exponent-2)[0]/exponent_minus_one,
            sum(b for a,b in pairs)
            + inverse_half_power(cutoff,twice_exponent-2)[1]/exponent_minus_one)


def pi_interval():
    # Machin identity, with alternating tails. Both arguments are positive.
    def arctan_bounds(den):
        partial = sum(F((-1)**j, (2*j+1)*den**(2*j+1)) for j in range(12))
        return partial, partial+F(1,25*den**25)
    a,b = arctan_bounds(5)
    c,d = arctan_bounds(239)
    return 16*a-4*d, 16*b-4*c


def tenth_order_value(twice_s, row):
    n = len(row)
    s = F(twice_s,2)
    pilo,pihi = pi_interval()
    zlo,zhi = real_zeta(2+4*n-twice_s)
    lower,upper = F(1),F(1)
    for r,coef in enumerate(row[:-1],1):
        power = 2*(n-r)
        coefficient = coef/row[-1]/prod(j-s for j in range(2*r+1,2*n+1))
        numlo,numhi = real_zeta(2+4*r-twice_s)
        lo = coefficient*(2*pilo)**power*numlo/zhi
        hi = coefficient*(2*pihi)**power*numhi/zlo
        if (n-r)%2:
            lower -= hi
            upper -= lo
        else:
            lower += lo
            upper += hi
    return lower,upper


def main():
    nmax = 26
    beta = beta_values(nmax)
    rows = {n:jordan_row(n,beta) for n in range(1,nmax+1)}
    for m in range(2,15):
        moments = newton_from_matrix(m-1, 18)
        for n in range(1,19):
            assert sum(a*(m**(2*r)-1) for r,a in enumerate(rows[n],1)) == moments[n]
    bern = bernoulli_values(2*nmax)
    actual_real = [None]+[-bern[2*r]/(2*r) for r in range(1,nmax+1)]
    zero, height14 = {}, {}
    for n in range(2,nmax+1):
        lo,hi = sum_enclosure(n,0,beta)
        assert lo == hi
        endpoint = sum(abs(a*actual_real[r]) for r,a in enumerate(rows[n][:-1],1))
        assert lo == endpoint/abs(beta[n]*actual_real[n])
        assert (lo>1 if n<=14 else lo<F(89,100))
        zero[n] = scaled_enclosure(lo,hi)
        if n <= 14:
            low14, high14 = sum_enclosure(n,14,beta)
            assert high14 < F(497,500)
            height14[n] = scaled_enclosure(low14,high14)
    assert max(height14, key=lambda n:height14[n][1]) == 7
    assert max(range(15,27), key=lambda n:zero[n][1]) == 15
    envelope = F(1)
    for r in range(2,28):
        envelope = 1+envelope_ratio(r)*envelope
    assert F(185,100) < envelope < F(186,100)
    assert envelope_ratio(28) < F(37,100)
    assert 1 + F(37,100)*F(186,100) < F(186,100)
    assert beta[2]/beta[3] == F(21,2)
    tenth = [tenth_order_value(twice_s,rows[10]) for twice_s in (0,1)]
    assert tenth[0][0] > F(13,100) and tenth[1][1] < -F(67,100)
    return {
        'task':'RS-EMW59A-1159-SPECTRAL-ZETA-JORDAN',
        'finite_tridiagonal_checks':{'matrix_M_inclusive':[2,14], 'orders_inclusive':[1,18],
                                    'equalities':13*18},
        'rational_endpoints_crosschecked_by_Bernoulli':25,
        'order_10_actual_normalized_numerator':{
            'real_limit_at_0':scaled_enclosure(*tenth[0]),
            'real_value_at_half':scaled_enclosure(*tenth[1]),
            'consequence':'a real numerator zero strictly between 0 and 1/2'},
        'decimal_enclosures':'[integers lo,hi] multiply by 10^-10; endpoints rounded outwards',
        'S_at_height_0':zero, 'S_at_height_14':height14,
        'envelope_at_27':scaled_enclosure(envelope,envelope),
        'envelope_ratio_at_28':str(envelope_ratio(28)),
        'unconditional_relative_lower_bounds':{
            'all_orders_above_height_14':'3/500','orders_at_least_15_entire_open_strip':'11/100'},
        'first_positive_zeta_zero_published':'14.1347251417346937904572519835625',
        'first_zero_input':'Platt; LMFDB zero 1, completeness by published Turing count; external input',
    }


if __name__ == '__main__':
    print(json.dumps(main(), ensure_ascii=False, indent=2))
