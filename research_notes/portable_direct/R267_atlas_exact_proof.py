"""Pure-Python exact certificate that eight affine planes give the entire lower envelope.
Input R267_verification.json is reproducibly generated by R267_six_price_cost_atlas.py.
"""
import json
from itertools import combinations
from fractions import Fraction as Q
from pathlib import Path

HERE=Path(__file__).parent
raw=json.loads((HERE/'R267_verification.json').read_text())
lines=[(v['a'],v['b9'],v['b26']) for v in raw['two_parameter_lines']]
active=[(16,168,2184),(16,2184,156),(160,2184,52),(196,0,2184),
        (208,2184,26),(2212,0,312),(2500,0,52),(2548,0,26)]
assert all(p in lines for p in active)

def solve(A,b):
    n=len(b)
    M=[[Q(v) for v in row]+[Q(w)] for row,w in zip(A,b)]
    for col in range(n):
        piv=next((r for r in range(col,n) if M[r][col]),None)
        if piv is None:return None
        M[col],M[piv]=M[piv],M[col]
        t=M[col][col];M[col]=[v/t for v in M[col]]
        for r in range(n):
            if r==col:continue
            v=M[r][col]
            if v:M[r]=[x-v*y for x,y in zip(M[r],M[col])]
    return [M[i][-1] for i in range(n)]

def dual_certificate(line):
    a,b,c=line; upper=(a+b+c,b,c)
    coeffs=[(a1+b1+c1,b1,c1) for a1,b1,c1 in active]
    for m in range(1,5):
        for inds in combinations(range(8),m):
            for tight in combinations(range(3),m-1):
                A=[[1]*m]+[[coeffs[i][t] for i in inds] for t in tight]
                B=[1]+[upper[t] for t in tight]
                sol=solve(A,B)
                if sol is None or min(sol)<0:continue
                if any(sum(sol[j]*coeffs[i][t] for j,i in enumerate(inds))>upper[t] for t in range(3)):continue
                return tuple((i,str(v)) for i,v in zip(inds,sol) if v)
    raise AssertionError(('no rational certificate',line))

def positive_witness(p):
    for d in (20,40,100,200,1000):
        for I in range(1,2*d):
            x=Q(d+I,d)
            for J in range(1,2*d):
                y=Q(d+J,d)
                if all((p[0]+p[1]*x+p[2]*y)<(q[0]+q[1]*x+q[2]*y) for q in active if q!=p):
                    return str(x),str(y)
    raise AssertionError(('no strict witness',p))

def main():
    certs={}
    for p in lines:
        certs[','.join(map(str,p))]=dual_certificate(p)
    witnesses={','.join(map(str,p)):positive_witness(p) for p in active}
    print('PASS exact duals',len(certs),'strict witnesses',len(witnesses))
    out={'schema':'R267_EIGHT_PLANE_EXACT_LOWER_ENVELOPE_CERTIFICATE_V1',
      'domain':'x>=1 and y>=1 (all other class costs 1)',
      'active_planes':[list(x) for x in active],
      'proof':'For each of 116 candidate planes (a,b,c), dual weights lambda>=0 sum to 1 and satisfy sum lambda*(a_j+b_j+c_j,b_j,c_j) <= (a+b+c,b,c). Thus min(active)<=candidate on x-1,y-1>=0. Strict witnesses establish each listed plane is active.',
      'dual_coefficients':certs,'strict_witnesses':witnesses}
    (HERE/'R267_atlas_certificate.json').write_text(json.dumps(out,indent=2,sort_keys=True)+'\n')
    return out
if __name__=='__main__':main()
