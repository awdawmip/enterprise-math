A5=matrix(((1,-1),(2,3)))
A7=matrix(((1,-2),(2,3)))


def canonical(n):
    a=b=0
    while n%5==0:
        a+=1;n//=5
    while n%7==0:
        b+=1;n//=7
    if n!=1:
        raise ValueError('probe uses only the multiplicative semigroup generated by 5,7')
    return mm(mpow(A5,a),mpow(A7,b))


def det2(a):
    return a[0][0]*a[1][1]-a[0][1]*a[1][0]


def holonomy_checks():
    first5=mm(A7,A5)
    first7=mm(A5,A7)
    assert first5==matrix(((-3,-7),(8,7)))
    assert first7==matrix(((-1,-5),(8,5)))
    h=mm(first5,inv(first7))
    assert h==matrix(((F(41,35),F(-8,35)),(F(-16,35),F(33,35))))
    assert det2(h)==1 and h!=eye(2)
    labels=[1,5,7,25,35,49]
    count=0
    for l,m,n in product(labels,repeat=3):
        dlm=factor_defect(canonical(l),canonical(m),canonical(l*m))
        dlmn=factor_defect(canonical(l*m),canonical(n),canonical(l*m*n))
        dmn=factor_defect(canonical(m),canonical(n),canonical(m*n))
        dl_mn=factor_defect(canonical(l),canonical(m*n),canonical(l*m*n))
        lhs=mm(dlm,dlmn)
        rhs=mm(mm(mm(canonical(l),dmn),inv(canonical(l))),dl_mn)
        assert lhs==rhs
        count+=1
    g=matrix(((1,1),(0,1)))
    ap=mm(mm(g,A5),inv(g));bp=mm(mm(g,A7),inv(g))
    hp=mm(mm(bp,ap),inv(mm(ap,bp)))
    assert hp==mm(mm(g,h),inv(g))
    assert sum(hp[i][i] for i in range(2))==F(74,35)
    record('03_noncommutative_defect_and_coherence',{'5_then_7':first5,'7_then_5':first7,
           'relative_defect':h,'defect_determinant':det2(h),'defect_trace':F(74,35),
           'twisted_cocycle_triples':count,'common_basis_conjugacy':'PASS',
           'scope':'chosen rational comparison maps, not global native rotations or lattice inverses'})


