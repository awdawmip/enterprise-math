def moment_checks():
    dim=6
    p=matrix([[int(i==(j+1)%dim) for j in range(dim)] for i in range(dim)])
    plus=Affine(p,(F(1),)+(F(0),)*5)
    minus=Affine(p,(F(-1),)+(F(0),)*5)
    step=EffectHistogram.from_terms(dim,[(1,plus,1),(1,minus,1)])
    moment=point_moment((0,)*dim)
    # Independent explicit path enumeration through 8 steps.
    raw=[((0,)*dim,F(1))]
    for depth in range(1,9):
        new=[]
        for x,w in raw:
            rotated=(x[-1],)+x[:-1]
            for sign in [-1,1]:
                new.append(((rotated[0]+sign,)+rotated[1:],w))
        raw=new
        moment=step.moment_action(moment)
        direct=sm(0,eye(dim+1))
        for x,w in raw:direct=ma(direct,sm(w,point_moment(x)))
        assert direct==moment
    # 32-step exact moment computation, NOT explicit enumeration of 2^32 paths.
    packed=MomentState.from_point((0,)*dim)
    hist=WeightHistogram.from_weights([1])
    for _ in range(32):
        packed=packed.then(step)
        assert len(packed.upper)==28
        hist=histogram_serial(hist,step.forget_effects())
    moment=packed.to_matrix()
    count=2**32
    assert hist.count==hist.total_mass==moment[-1][-1]==count
    covariance=tuple(tuple(moment[i][j]/count for j in range(dim)) for i in range(dim))
    assert covariance==matrix([[([6,6,5,5,5,5][i] if i==j else 0) for j in range(dim)] for i in range(dim)])
    assert all(moment[i][-1]==0 for i in range(dim))
    record('09_affine_moment_closure',{'explicit_path_depth':8,'paths_at_depth8':len(raw),
           'compressed_depth':32,'represented_path_count':count,'symmetric_rational_entries':28,
           'total_mass':hist.total_mass,'normalized_covariance':covariance,
           'path_enumeration_at_depth32':False,
           'scope':'degree<=2 affine future observations only; no constant bit-memory claim'})


