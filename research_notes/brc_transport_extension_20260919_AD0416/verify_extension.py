def carry_checks():
    tested=0
    for x in range(-250,251):
        for bases in [(5,7),(7,5),(5,5),(5,7,5)]:
            q,r=euclidean_digits(x,bases)
            assert recompose(q,r,bases)==x
            modulus=1
            for b in bases:modulus*=b
            assert q==x//modulus
            assert recompose(0,r,bases)==x%modulus
            tested+=1
        assert euclidean_digits(x,(5,7))[0]==euclidean_digits(x,(7,5))[0]
    record('07_remainder_lift_and_exact_recomposition',{'round_trips':tested,
           '17_base5_then7':euclidean_digits(17,(5,7)),
           '17_base7_then5':euclidean_digits(17,(7,5)),
           'scope':'digit ordering differs, final scalar remainder is canonically convertible'})


