T = {}
for token in DATA.split():
    a,b,v = map(int,token.split(','))
    assert a >= 0 and b != 0 and (a,b) not in ((2,1),(1,-1))
    assert 20 <= v <= 40 and v != 20 and (a,b) not in T
    T[(a,b)] = v
assert len(T)==524
def q40(x,y):
    a=abs(x)
    if a==0 and y==0: return 0
    if y==0: return DEN
    if (a,y) in ((2,1),(1,-1)): return 20
    return T.get((a,y),20)
def defect40(z):
    t=tuple(sum(row[i]*z[i] for i in range(4)) for row in A)
    return q40(t[0],t[1])+q40(t[2],t[3])-q40(z[0],z[1])-q40(z[2],z[3])
assert q40(0,0)==0 and q40(2,1)==q40(-1,-1)==20
for x in range(-30,31):
    for y in range(-30,31):
        assert q40(x,y)==q40(-x,y)
        assert q40(x,y)>=20 if (x,y)!=(0,0) else q40(x,y)==0
        if y==0 and x!=0: assert q40(x,y)==40
hist=Counter()
for z in product(range(-B,B+1),repeat=4):
    hist[defect40(z)]+=1
assert sum(hist.values())==17**4==83521
assert max(map(abs,hist))==20
assert defect40((1,-1,0,0))==20
assert sum(v for d,v in hist.items() if abs(d)==20)==3176
