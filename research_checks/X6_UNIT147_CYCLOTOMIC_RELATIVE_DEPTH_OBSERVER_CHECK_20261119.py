D = (1,)*6
SLICES = tuple(combinations(range(6), 3))

def U(z):
    t=z[-1]
    return (-t, *(z[i]-t for i in range(5)))

def phase(z, r):
    for _ in range(r): z=U(z)
    return z

def obs(z, S):
    v=[z[j] for j in S]
    a=min(v)
    return tuple(x-a for x in v)

def chart(z):
    m=min(z)
    return tuple(a-m for a in z),m

def n_brc(z):
    n=sum(abs(a) for a in z)
    v=math.factorial(n)
    for a in z: v//=math.factorial(abs(a))  # exact: sequential division valid multinomial
    return v

