#!/usr/bin/env python3
from collections import deque

STATES=tuple((r,e) for r in range(6) for e in (-1,1))
INDEX={s:i for i,s in enumerate(STATES)}


def advance(s):
    r,e=s; return ((r+e)%6,e)


def reverse_event(s):
    r,e=s; return ((r+e)%6,-e)


def advance_inv(s):
    r,e=s; return ((r-e)%6,e)


def iterate(f,s,n):
    for _ in range(n): s=f(s)
    return s


def perm(f):
    return tuple(INDEX[f(s)] for s in STATES)


def compose(g,h):
    return tuple(g[h[i]] for i in range(len(STATES)))


# Same immediate phase, opposite hidden chirality and distinct one-step future.
for s in STATES:
    a=advance(s); b=reverse_event(s)
    assert a[0]==b[0]
    assert a[1]==-b[1]
    assert advance(a)[0] != advance(b)[0]

# Exact D12 presentation.
for s in STATES:
    assert iterate(advance,s,6)==s
    assert reverse_event(reverse_event(s))==s
    assert reverse_event(advance(reverse_event(s)))==advance_inv(s)

A=perm(advance); B=perm(reverse_event); I=tuple(range(len(STATES)))
G={I}; queue=deque([I])
while queue:
    x=queue.popleft()
    for g in (A,B):
        y=compose(g,x)
        if y not in G:
            G.add(y); queue.append(y)
assert len(G)==12

# Regular action: one state has orbit 12, hence trivial stabilizer.
base=INDEX[(0,1)]
assert len({g[base] for g in G})==12
assert sum(g[base]==base for g in G)==1

# Exact predictive minimality: any two distinct states are separated by
# current phase or by one ADVANCE phase future.
for i,s in enumerate(STATES):
    for t in STATES[i+1:]:
        separated = (s[0]!=t[0]) or (advance(s)[0]!=advance(t)[0])
        assert separated

# Phase-only and chirality-only quotients are unsafe.
assert any(s[0]==t[0] and advance(s)[0]!=advance(t)[0]
           for s in STATES for t in STATES if s!=t)
assert any(s[1]==t[1] and s[0]!=t[0]
           for s in STATES for t in STATES)

# C6 subgroup generated by A has 6 elements; D12/C6 has two cosets.
C6={I}; x=I
for _ in range(5):
    x=compose(A,x); C6.add(x)
assert len(C6)==6
odd_coset={compose(g,B) for g in C6}
assert len(odd_coset)==6 and C6.isdisjoint(odd_coset)
assert C6|odd_coset==G

# Word charge = parity of B occurrences is compatible with the quotient.
words=[(),('A',),('B',),('A','B'),('B','A'),('B','B'),('A','B','A','B')]
for word in words:
    g=I; bcount=0
    for letter in word:
        if letter=='A': g=compose(A,g)
        else:
            g=compose(B,g); bcount+=1
    assert (g in odd_coset)==bool(bcount%2)

print('PASS_X6_PHASE_CHIRALITY_D12_V14')
print('predictive_states',len(STATES))
print('event_group_order',len(G))
print('advance_subgroup_order',len(C6))
print('phase_reversal_coset_size',len(odd_coset))
print('phase_only_operation_safe',False)
print('phase_x_chirality_minimal',True)
