"""Operation-language fixed-point repair for the R007 finite precision program.

Executable evidence only; this module records exact finite theorem targets, not Lean proofs.

For a finite state set X, an observation partition E, and an operation monoid A,
the coarsest A-stable refinement is the Nerode/Moore repair

    R_A(E) = intersection_{a in A} a^{-1}(E).

When two operation monoids admit a normal form B o A (equivalently A o B can
be rewritten into B o A), the joint repair factors in the reverse pullback order:

    R_<A,B>(E) = R_A(R_B(E)).

The prime-power helpers specialize this to the divisor-depth observation on
Z/p^beta Z.  Translation granularity p^(beta-r), together with all
multiplications, forces exactly r significant p-adic phase digits at every
shallow valuation shell.  Thus the joint affine quotient is a finite
"valuation + significant digits" precision model.
"""

from __future__ import annotations

from typing import Hashable, Iterable, Sequence

Partition = tuple[int, ...]
Endomap = tuple[int, ...]


def canonical_partition(labels: Iterable[Hashable]) -> Partition:
    table: dict[Hashable, int] = {}
    out: list[int] = []
    for label in labels:
        if label not in table:
            table[label] = len(table)
        out.append(table[label])
    return tuple(out)


def map_tuple(size: int, fn) -> Endomap:
    if size < 0:
        raise ValueError("size must be nonnegative")
    out = tuple(fn(i) for i in range(size))
    if any(value < 0 or value >= size for value in out):
        raise ValueError("endomap left the finite state set")
    return out


def operation_respects_partition(partition: Partition, operation: Endomap) -> bool:
    if len(partition) != len(operation):
        raise ValueError("partition and operation sizes differ")
    images: dict[int, int] = {}
    for state, block in enumerate(partition):
        image_block = partition[operation[state]]
        old = images.setdefault(block, image_block)
        if old != image_block:
            return False
    return True


def repair_step(partition: Partition, operations: Sequence[Endomap]) -> Partition:
    """One Moore refinement step using the current blocks of operation images."""
    size = len(partition)
    if any(len(op) != size for op in operations):
        raise ValueError("operation size mismatch")
    return canonical_partition(
        (partition[state], *(partition[op[state]] for op in operations))
        for state in range(size)
    )


def repair_partition(partition: Partition, operations: Sequence[Endomap]) -> Partition:
    """Least refinement stable under the monoid generated by ``operations``."""
    current = canonical_partition(partition)
    while True:
        nxt = repair_step(current, operations)
        if nxt == current:
            return current
        current = nxt


def ordered_two_stage_repair(
    partition: Partition,
    first_monoid_ops: Sequence[Endomap],
    second_monoid_ops: Sequence[Endomap],
) -> Partition:
    """R_A(R_B(E)) for a normal form ``B o A``.

    The argument names reflect the semantic application order: first A, then B.
    Pullback repair is contravariant, so the B-repair is performed before the
    A-repair.
    """
    repaired_by_second = repair_partition(partition, second_monoid_ops)
    return repair_partition(repaired_by_second, first_monoid_ops)


def truncated_p_valuation(residue: int, p: int, beta: int) -> int:
    if p < 2 or beta < 0:
        raise ValueError("require p>=2 and beta>=0")
    modulus = p**beta
    if modulus == 1:
        return 0
    residue %= modulus
    if residue == 0:
        return beta
    value = 0
    while residue % p == 0:
        residue //= p
        value += 1
    return value


def valuation_shadow_partition(p: int, beta: int) -> Partition:
    modulus = p**beta
    return canonical_partition(
        truncated_p_valuation(residue, p, beta)
        for residue in range(modulus)
    )


def translation_generator(p: int, beta: int, phase_digits: int) -> Endomap:
    """Generator +p^(beta-r) for r significant phase digits."""
    if not 0 <= phase_digits <= beta:
        raise ValueError("require 0 <= phase_digits <= beta")
    modulus = p**beta
    step = p ** (beta - phase_digits)
    return map_tuple(modulus, lambda x: (x + step) % modulus)


def all_multiplier_maps(p: int, beta: int) -> tuple[Endomap, ...]:
    modulus = p**beta
    return tuple(
        map_tuple(modulus, lambda x, a=a: (a * x) % modulus)
        for a in range(modulus)
    )


def translation_only_label(residue: int, p: int, beta: int, phase_digits: int):
    """Exact translation-only Nerode label.

    Put s=beta-r.  Shells v_p(n)<s need only their valuation.  The deep ball
    p^s Z/p^beta Z must retain its full normalized residue modulo p^r.
    """
    if not 0 <= phase_digits <= beta:
        raise ValueError("require 0 <= phase_digits <= beta")
    modulus = p**beta
    residue %= modulus
    s = beta - phase_digits
    value = truncated_p_valuation(residue, p, beta)
    if value < s:
        return ("valuation", value)
    return ("core", (residue // (p**s)) % (p**phase_digits))


def affine_significant_label(residue: int, p: int, beta: int, phase_digits: int):
    """Exact joint multiplication+translation Nerode label.

    Equivalent descriptions:

    * d=p^min(v_p(n),s), together with (n/d) mod p^r;
    * truncated valuation plus r significant p-adic digits, capped by total
      modulus precision beta.
    """
    if not 0 <= phase_digits <= beta:
        raise ValueError("require 0 <= phase_digits <= beta")
    modulus = p**beta
    residue %= modulus
    s = beta - phase_digits
    value = truncated_p_valuation(residue, p, beta)
    if value < s:
        unit = (residue // (p**value)) % (p**phase_digits)
        return ("shell", value, unit)
    return ("core", (residue // (p**s)) % (p**phase_digits))


def significant_digit_label(residue: int, p: int, beta: int, phase_digits: int):
    """Alternative ``valuation + relative significant digits`` presentation."""
    if not 0 <= phase_digits <= beta:
        raise ValueError("require 0 <= phase_digits <= beta")
    modulus = p**beta
    residue %= modulus
    value = truncated_p_valuation(residue, p, beta)
    if value == beta:
        return (beta, 0)
    precision = min(beta, value + phase_digits)
    return (value, residue % (p**precision) if precision else 0)


def euler_phi_prime_power(p: int, exponent: int) -> int:
    if p < 2 or exponent < 0:
        raise ValueError("require p>=2 and exponent>=0")
    if exponent == 0:
        return 1
    return p ** (exponent - 1) * (p - 1)


def translation_repair_count(p: int, beta: int, phase_digits: int) -> int:
    """Number of repeated-translation future states: (beta-r)+p^r."""
    if not 0 <= phase_digits <= beta:
        raise ValueError("require 0 <= phase_digits <= beta")
    return beta - phase_digits + p**phase_digits


def affine_repair_count(p: int, beta: int, phase_digits: int) -> int:
    """Number of joint multiplier+translation future states.

    K(beta,r)=p^r+(beta-r)*phi(p^r).
    """
    if not 0 <= phase_digits <= beta:
        raise ValueError("require 0 <= phase_digits <= beta")
    return p**phase_digits + (beta - phase_digits) * euler_phi_prime_power(
        p, phase_digits
    )


def translation_phase_tick_increment(p: int, beta: int, phase_digits: int) -> int:
    """New states when translation precision r increases to r+1."""
    if not 0 <= phase_digits < beta:
        raise ValueError("require 0 <= phase_digits < beta")
    return (p - 1) * p**phase_digits - 1


def affine_phase_tick_increment(p: int, beta: int, phase_digits: int) -> int:
    """New joint affine states when significant precision r increases to r+1."""
    if not 0 <= phase_digits < beta:
        raise ValueError("require 0 <= phase_digits < beta")
    if phase_digits == 0:
        return beta * (p - 2)
    return (
        (beta - phase_digits)
        * (p - 1) ** 2
        * p ** (phase_digits - 1)
    )


def multiplication_interference_cost(p: int, beta: int, phase_digits: int) -> int:
    """Extra states needed to restore multiplication after translation repair."""
    if not 0 <= phase_digits <= beta:
        raise ValueError("require 0 <= phase_digits <= beta")
    s = beta - phase_digits
    return s * (euler_phi_prime_power(p, phase_digits) - 1)


def first_significant_phase_precision(
    left: int, right: int, p: int, beta: int
) -> int | None:
    """Least r for which the affine significant-digit quotients distinguish residues.

    Different valuation shells are already distinguished at r=0.  On one shell
    j, the required phase precision is one more than the p-adic agreement depth
    of the normalized units.
    """
    modulus = p**beta
    left %= modulus
    right %= modulus
    if left == right:
        return None
    jl = truncated_p_valuation(left, p, beta)
    jr = truncated_p_valuation(right, p, beta)
    if jl != jr:
        return 0
    diff = (left - right) % modulus
    agreement = truncated_p_valuation(diff, p, beta)
    return agreement - jl + 1
