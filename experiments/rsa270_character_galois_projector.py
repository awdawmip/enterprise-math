#!/usr/bin/env python3
"""
Primitive-character Galois projector for the multiplied BRC profile.

Checks:
A_chi(n) = chi(2)/2 * Pi_chi( (zeta^2-1)/(2 zeta) * P_(3^e n)(zeta) ).

Researcher-ID: EM-DIRECT-66DE45
No RSA factor is used or produced.
"""
import cmath
import math


def divisors(n):
    out = []
    d = 1
    while d * d <= n:
        if n % d == 0:
            out.append(d)
            if d * d != n:
                out.append(n // d)
        d += 1
    return sorted(out)


def character_data(e):
    m = 3 ** e
    L = 2 * 3 ** (e - 1)
    xi = cmath.exp(2j * math.pi / L)
    log = {}
    x = 1
    for k in range(L):
        log[x] = k
        x = (2 * x) % m
    assert len(log) == L

    def chi(a):
        a %= m
        if math.gcd(a, m) != 1:
            return 0j
        return xi ** log[a]

    return m, L, xi, chi


def projected_normalized_profile(n, e):
    assert n % 2 == 1 and n % 3 != 0
    m, L, xi, chi = character_data(e)
    T = m * n
    val = 0j
    for d in divisors(T):
        comp = T // d
        R = d + comp
        assert R % 2 == 0
        t = (R // 2) % m
        # D=(zeta^2-1)/(2zeta): each W block becomes
        # 1/2*(zeta^t-zeta^-t).
        val += 0.5 * (chi(t) - chi(-t))
    A = sum(chi(d) for d in divisors(n))
    rhs = 2 * A / chi(2)
    return val, rhs, A


def check_projector():
    ns = [5, 7, 11, 25, 35, 55, 77, 175]
    total = 0
    for e in range(2, 6):
        for n in ns:
            if n % 3 == 0:
                continue
            v, r, A = projected_normalized_profile(n, e)
            assert abs(v - r) < 1e-8, (e, n, v, r)
            total += 1
    return total


def check_intermediate_annihilation():
    total = 0
    for e in range(2, 7):
        m = 3 ** e
        for n in [5, 7, 25, 35, 55]:
            for a in divisors(n):
                for j in range(1, e):
                    d = (3 ** j) * a
                    comp = (3 ** (e - j)) * (n // a)
                    t = ((d + comp) // 2) % m
                    assert t % 3 == 0
                    total += 1
    return total


def check_gauss_projector_monomials():
    total = 0
    for e in range(2, 5):
        m, L, xi, chi = character_data(e)
        zeta = cmath.exp(2j * math.pi / m)
        units = [a for a in range(m) if math.gcd(a, m) == 1]
        tau = sum(chi(a).conjugate() * (zeta ** a) for a in units)
        assert abs(tau) > 1e-8
        for t in range(m):
            lhs = sum(chi(a).conjugate() * (zeta ** (a * t)) for a in units) / tau
            rhs = chi(t)
            assert abs(lhs - rhs) < 1e-8, (e, t, lhs, rhs)
            total += 1
    return total


def conv(a, b):
    out = [0j] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            out[i + j] += x * y
    return out


def check_radix3_factorization():
    # 3-primary part of U(3^e) is generated by 4, order 3^(e-1).
    # Sum_k eta_bar^k Y^k factorizes digitwise in base 3.
    total = 0
    for e in range(2, 7):
        L = 3 ** (e - 1)
        eta = cmath.exp(2j * math.pi / L)
        poly = [1 + 0j]
        for j in range(e - 1):
            step = 3 ** j
            f = [0j] * (2 * step + 1)
            f[0] = 1
            f[step] = eta.conjugate() ** step
            f[2 * step] = eta.conjugate() ** (2 * step)
            poly = conv(poly, f)
        assert len(poly) == L
        dense = [eta.conjugate() ** k for k in range(L)]
        assert max(abs(a - b) for a, b in zip(poly, dense)) < 1e-8
        total += 1
    return total


if __name__ == "__main__":
    print("profile projector cases:", check_projector(), "PASS")
    print("intermediate annihilation:", check_intermediate_annihilation(), "PASS")
    print("Gauss monomial projector:", check_gauss_projector_monomials(), "PASS")
    print("radix-3 factorization levels:", check_radix3_factorization(), "PASS")
    print("ALL PASS")
