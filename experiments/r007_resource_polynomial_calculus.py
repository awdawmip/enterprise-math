"""Resource-polynomial calculus for Stage131-style fixed operation compilers.

Executable evidence only; formulas here package already-derived finite combinatorics.

For a lower-set mask compiler on a finite poset P, the antichain polynomial

    A_P(z) = sum_{A antichain} z^|A|

is the exact shortest-depth spectrum: A_P(1)-1 is the nonidentity semantic
one-step table, [z]A_P is primitive storage, and deg A_P is worst depth.

Two poset compositions become exact compiler resource operations:

* parallel/disjoint union: A_{P sqcup Q} = A_P * A_Q;
* serial/ordinal sum:       A_{P plus Q} = A_P + A_Q - 1.

The divisor prime-power chains are a special case.  The module also compares
three instruction semantics on one divisor state lattice: gcd caps, saturating
upward shifts, and the monoid generated by both.
"""

from __future__ import annotations

from math import comb
from typing import Iterable

Polynomial = tuple[int, ...]


def trim(poly: Iterable[int]) -> Polynomial:
    values = list(poly)
    while len(values) > 1 and values[-1] == 0:
        values.pop()
    return tuple(values or [0])


def poly_add(left: Polynomial, right: Polynomial) -> Polynomial:
    size = max(len(left), len(right))
    return trim(
        (left[i] if i < len(left) else 0) + (right[i] if i < len(right) else 0)
        for i in range(size)
    )


def poly_mul(left: Polynomial, right: Polynomial) -> Polynomial:
    out = [0] * (len(left) + len(right) - 1)
    for i, a in enumerate(left):
        for j, b in enumerate(right):
            out[i + j] += a * b
    return trim(out)


def parallel_resource(left: Polynomial, right: Polynomial) -> Polynomial:
    return poly_mul(left, right)


def serial_resource(left: Polynomial, right: Polynomial) -> Polynomial:
    out = list(poly_add(left, right))
    out[0] -= 1
    return trim(out)


def singleton_resource() -> Polynomial:
    return (1, 1)


def chain_resource(length: int) -> Polynomial:
    if length < 0:
        raise ValueError("length must be nonnegative")
    return (1, length) if length else (1,)


def antichain_resource(size: int) -> Polynomial:
    if size < 0:
        raise ValueError("size must be nonnegative")
    return tuple(comb(size, k) for k in range(size + 1))


def disjoint_chain_resource(lengths: Iterable[int]) -> Polynomial:
    result: Polynomial = (1,)
    for length in lengths:
        if length < 1:
            raise ValueError("chain lengths must be positive")
        result = poly_mul(result, (1, length))
    return result


def resource_summary(poly: Polynomial) -> tuple[int, int, int]:
    poly = trim(poly)
    table = sum(poly) - 1
    primitive = poly[1] if len(poly) > 1 else 0
    worst = len(poly) - 1
    return table, primitive, worst


def gcd_cap_resource(exponents: Iterable[int]) -> Polynomial:
    return disjoint_chain_resource(tuple(exponents))


def saturating_shift_resource(exponents: Iterable[int]) -> Polynomial:
    result: Polynomial = (1,)
    for alpha in exponents:
        if alpha < 1:
            raise ValueError("exponents must be positive")
        result = poly_mul(result, tuple(1 for _ in range(alpha + 1)))
    return result


def local_cap_shift_resource(alpha: int) -> Polynomial:
    if alpha < 1:
        raise ValueError("alpha must be positive")
    return (1, *(alpha - depth + 2 for depth in range(1, alpha + 1)))


def cap_shift_resource(exponents: Iterable[int]) -> Polynomial:
    result: Polynomial = (1,)
    for alpha in exponents:
        result = poly_mul(result, local_cap_shift_resource(alpha))
    return result


def cap_shift_semantic_count_formula(exponents: Iterable[int]) -> int:
    result = 1
    for alpha in exponents:
        if alpha < 1:
            raise ValueError("exponents must be positive")
        result *= comb(alpha + 2, 2)
    return result
