"""Additive phase repair for the R007 divisor-shadow collapse.

Executable evidence only; these are finite arithmetic theorem targets, not Lean proofs.

For a positive ceiling C, the divisor shadow

    rho_C(n) = gcd(n, C)

forgets the unit/residue phase of n modulo C.  Multiplication descends through
this shadow exactly, while addition generally does not.  A fixed translation
n -> n+t is shadow-safe precisely when C/gcd(C,2) divides t.  When it is not
safe, the exact minimal future-compatible repair size under repeated t-steps is

    product_{p^beta || C} (s_p + p^(beta-s_p)),

where s_p=min(v_p(t), beta).  In particular a unit step forces the complete
residue phase modulo C.
"""

from __future__ import annotations

from math import gcd


def factor_exponents(n: int) -> dict[int, int]:
    if n < 1:
        raise ValueError("n must be positive")
    out: dict[int, int] = {}
    p = 2
    while p * p <= n:
        while n % p == 0:
            out[p] = out.get(p, 0) + 1
            n //= p
        p = 3 if p == 2 else p + 2
    if n > 1:
        out[n] = out.get(n, 0) + 1
    return out


def p_adic_valuation(n: int, p: int) -> int:
    if n < 0 or p < 2:
        raise ValueError("require n>=0 and p>=2")
    if n == 0:
        raise ValueError("valuation of zero is not finite here")
    value = 0
    while n % p == 0:
        n //= p
        value += 1
    return value


def divisors(n: int) -> tuple[int, ...]:
    if n < 1:
        raise ValueError("n must be positive")
    values = [1]
    for p, exponent in factor_exponents(n).items():
        values = [
            value * p**power
            for value in values
            for power in range(exponent + 1)
        ]
    return tuple(sorted(values))


def euler_phi(n: int) -> int:
    if n < 1:
        raise ValueError("n must be positive")
    result = n
    for p in factor_exponents(n):
        result -= result // p
    return result


def divisor_shadow(residue: int, ceiling: int) -> int:
    if ceiling < 1:
        raise ValueError("ceiling must be positive")
    return gcd(residue % ceiling, ceiling)


def shadow_product(a: int, b: int, ceiling: int) -> int:
    """Induced multiplication on divisor shadows: gcd(a*b,C)."""
    if ceiling < 1 or ceiling % a or ceiling % b:
        raise ValueError("a and b must divide the ceiling")
    return gcd(a * b, ceiling)


def principal_ideal(residue: int, ceiling: int) -> frozenset[int]:
    """Principal ideal generated by residue in Z/ceiling Z, as residue values."""
    if ceiling < 1:
        raise ValueError("ceiling must be positive")
    r = residue % ceiling
    return frozenset((r * k) % ceiling for k in range(ceiling))


def shadow_fiber(ceiling: int, shadow: int) -> frozenset[int]:
    if ceiling < 1 or shadow < 1 or ceiling % shadow:
        raise ValueError("shadow must divide the positive ceiling")
    return frozenset(r for r in range(ceiling) if divisor_shadow(r, ceiling) == shadow)


def units_mod(ceiling: int) -> frozenset[int]:
    if ceiling < 1:
        raise ValueError("ceiling must be positive")
    return frozenset(r for r in range(ceiling) if gcd(r, ceiling) == 1)


def unit_orbit(residue: int, ceiling: int) -> frozenset[int]:
    if ceiling < 1:
        raise ValueError("ceiling must be positive")
    r = residue % ceiling
    return frozenset((u * r) % ceiling for u in units_mod(ceiling))


def translation_safe_step(ceiling: int) -> int:
    """Least positive t for which rho_C(n+t) depends only on rho_C(n)."""
    if ceiling < 1:
        raise ValueError("ceiling must be positive")
    return ceiling // gcd(ceiling, 2)


def translation_is_shadow_safe(ceiling: int, step: int) -> bool:
    if ceiling < 1:
        raise ValueError("ceiling must be positive")
    return step % translation_safe_step(ceiling) == 0


def induced_translation(ceiling: int, step: int, shadow: int) -> int:
    """Induced shadow output for one translation, requiring shadow-safety."""
    if not translation_is_shadow_safe(ceiling, step):
        raise ValueError("translation is not shadow-safe")
    fiber = shadow_fiber(ceiling, shadow)
    outputs = {divisor_shadow(r + step, ceiling) for r in fiber}
    if len(outputs) != 1:
        raise AssertionError("shadow-safety invariant failed")
    return next(iter(outputs))


def translation_repair_class_count(ceiling: int, step: int) -> int:
    """Exact minimal Moore/future-equivalence state count under repeated +step."""
    if ceiling < 1:
        raise ValueError("ceiling must be positive")
    result = 1
    step_abs = abs(step)
    for p, beta in factor_exponents(ceiling).items():
        if step_abs == 0:
            s = beta
        else:
            s = min(p_adic_valuation(step_abs, p), beta)
        result *= s + p ** (beta - s)
    return result


def translation_trace(residue: int, ceiling: int, step: int) -> tuple[int, ...]:
    """One full residue-period output trace under repeated translation."""
    if ceiling < 1:
        raise ValueError("ceiling must be positive")
    period = ceiling // gcd(ceiling, step)
    return tuple(
        divisor_shadow(residue + k * step, ceiling)
        for k in range(period)
    )


def moore_partition(ceiling: int, step: int) -> tuple[frozenset[int], ...]:
    """Exact future-equivalence partition determined by infinite translation traces."""
    if ceiling < 1:
        raise ValueError("ceiling must be positive")
    groups: dict[tuple[int, ...], set[int]] = {}
    for residue in range(ceiling):
        trace = translation_trace(residue, ceiling, step)
        groups.setdefault(trace, set()).add(residue)
    return tuple(
        sorted(
            (frozenset(group) for group in groups.values()),
            key=lambda group: (min(group), len(group)),
        )
    )


def addition_descends(ceiling: int) -> bool:
    """Binary addition descends through rho_C exactly for C=1 or C=2."""
    if ceiling < 1:
        raise ValueError("ceiling must be positive")
    return ceiling <= 2


def additive_repair_fiber_size(ceiling: int, shadow: int) -> int:
    """Residue phases hidden in one divisor-shadow fiber: phi(C/shadow)."""
    if ceiling < 1 or shadow < 1 or ceiling % shadow:
        raise ValueError("shadow must divide the positive ceiling")
    return euler_phi(ceiling // shadow)
